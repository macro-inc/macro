import $RefParser from '@apidevtools/json-schema-ref-parser';
import { $ } from 'bun';
import { jsonSchemaToZod } from 'json-schema-to-zod';
import { resolve } from 'node:path';
import { z } from 'zod';

const ROOT = resolve(import.meta.dirname, '../../..');
const SOURCE = resolve(ROOT, 'crates/client/cache-core/src/engine/authority/schema.json');
const OUTPUT = resolve(import.meta.dirname, '../src/lib/graphql-cache/authority.generated.ts');
const DOCUMENT = z.object({
  schemas: z.record(z.string(), z.record(z.string(), z.unknown())),
});

if (process.argv.includes('--rust')) {
  const json = await $`cargo run --quiet -p cache-core --features schema --example authority_schema`.cwd(ROOT).text();
  if (process.argv.includes('--check')) {
    if (json !== await Bun.file(SOURCE).text()) throw new Error('Rust permission schemas are stale');
  } else await Bun.write(SOURCE, json);
}
const document = DOCUMENT.parse(await Bun.file(SOURCE).json());
const parts = ['// Generated by scripts/generate-cache-authority-schema.ts. Do not edit.', "import { z } from 'zod/v3';"];
for (const [name, schema] of Object.entries(document.schemas)) {
  const resolved = await $RefParser.dereference(structuredClone(schema));
  parts.push(jsonSchemaToZod(resolved, {
    module: 'esm', name: `${name}Schema`, noImport: true, withoutDescribes: true,
  }));
  parts.push(`export type ${name} = z.infer<typeof ${name}Schema>;`);
}
const input = Buffer.from(parts.join('\n\n'));
const output = await $`${process.env.BIOME_BINARY ?? 'biome'} format --stdin-file-path=${OUTPUT} < ${input}`.cwd(resolve(ROOT, 'apps/web')).text();
if (!output.trim()) throw new Error('Permission transport formatter produced no output');
if (process.argv.includes('--check')) {
  if (await Bun.file(OUTPUT).text() !== output) throw new Error('Generated permission transport is stale');
} else await Bun.write(OUTPUT, output);
