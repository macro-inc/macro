[[package]]
name = "patched"
version = "1.0.0"
dependencies = ["miniz"]

[[package]]
name = "miniz"
version = "0.8.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "gggg"

[[package]]
name = "png"
version = "0.17.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbb"

[[package]]
