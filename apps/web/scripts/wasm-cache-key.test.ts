const WORKSPACE = new Set(['engine', 'server']);

const MANIFEST = `[workspace]
resolver = "2"
members = [
  "crates/engine",
  "crates/server",
]

[workspace.dependencies]
png = "0.17"

[profile.engine-wasm]
inherits = "release"
lto = true
`;

const temporaryDirectories: string[] = [];
afterEach(() => {
  for (const directory of temporaryDirectories.splice(0)) {
    rmSync(directory, { recursive: true, force: true });
  }
});

function workspace(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'wasm-cache-key-'));
  temporaryDirectories.push(root);
  for (const [path, contents] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), contents);
  }
  symlinkSync('../../AGENTS.md', join(root, 'crates/engine/CLAUDE.md'));
  spawnSync('git', ['init', '-q'], { cwd: root });
  spawnSync('git', ['add', '-A'], { cwd: root });
  return root;
}

const BASE_FILES = {
  'Cargo.toml': MANIFEST,
  'Cargo.lock': LOCK,
  'rust-toolchain.toml': '[toolchain]\nchannel = "1.94.0"\n',
  'nix/tools.nix': '{ wasm-pack = "0.15.0"; }\n',
  '.github/workspace-dep-closures.json': JSON.stringify({
    // The plain closure also follows a link a wasm32 build never compiles.
    closures: { engine: ['crates/engine', 'crates/server'], server: ['crates/server'] },
    wasm_closures: { engine: ['crates/engine'] },
  }),
  'crates/engine/Cargo.toml': '[package]\nname = "engine"\nversion = "0.1.0"\n',
  'crates/engine/src/lib.rs': 'pub fn draw() {}\n',
  'crates/server/Cargo.toml': '[package]\nname = "server"\nversion = "0.1.0"\n',
  'crates/server/src/main.rs': 'fn main() {}\n',
};

const BUILD = ['wasm-pack', 'build', 'crates/engine', '--profile', 'engine-wasm'];

function key(files: Record<string, string>, env: Record<string, string> = {}) {
  return wasmCacheKey(workspace({ ...BASE_FILES, ...files }), 'engine', BUILD, env);
}

describe('lockSlice', () => {
  it('follows locked dependencies, choosing the named version', () => {
    const slice = lockSlice(LOCK, ['engine'], WORKSPACE).join('\n');
    expect(slice).toContain('name = "png"');
    expect(slice).toContain('checksum = "bbbb"');
    expect(slice).not.toContain('checksum = "cccc"');
    expect(slice).not.toContain('name = "tokio"');
  });

  it('stops at workspace crates the build does not compile', () => {
    // engine's lock entry lists server, a dependency it has only off wasm32.
    const slice = lockSlice(LOCK, ['engine'], WORKSPACE).join('\n');
    expect(slice).not.toContain('name = "server"');
    expect(slice).not.toContain('checksum = "cccc"');
    // A path dependency outside the workspace (a `[patch]`) has no source
    // either, and is followed.
    expect(slice).toContain('checksum = "gggg"');

    const both = lockSlice(LOCK, ['engine', 'server'], WORKSPACE).join('\n');
    expect(both).toContain('name = "server"');
    expect(both).toContain('name = "tokio"');
  });
});

describe('manifestWithoutMembers', () => {
  it('drops only the member list', () => {
    const manifest = manifestWithoutMembers(MANIFEST);
    expect(manifest).not.toContain('crates/server');
    expect(manifest).toContain('resolver = "2"');
    expect(manifest).toContain('png = "0.17"');
    expect(manifest).toContain('[profile.engine-wasm]');
  });
});

describe('profileEnvPrefix', () => {
  it('reads --profile, and release otherwise', () => {
    expect(profileEnvPrefix(BUILD)).toBe('CARGO_PROFILE_ENGINE_WASM_');
    expect(profileEnvPrefix(['wasm-pack', 'build', '--release'])).toBe(
      'CARGO_PROFILE_RELEASE_'
    );
  });
});

describe('wasmCacheKey', () => {
  it('keeps the key when only packages outside the build change', () => {
    const base = key({});
    expect(key({ 'crates/server/src/main.rs': 'fn main() { run() }\n' })).toBe(base);
    expect(
      key({ 'Cargo.lock': LOCK.replace('version = "1.40.0"', 'version = "1.41.0"') })
    ).toBe(base);
    expect(
      key({ 'Cargo.toml': MANIFEST.replace('"crates/server",', '"crates/server",\n  "crates/new",') })
    ).toBe(base);
    expect(key({}, { CARGO_PROFILE_OTHER_WASM_LTO: 'off' })).toBe(base);
  });

  it('changes the key when anything the build reads changes', () => {
    const base = key({});
    const changed = [
      key({ 'crates/engine/src/lib.rs': 'pub fn draw() { paint() }\n' }),
      key({ 'Cargo.lock': LOCK.replace('checksum = "aaaa"', 'checksum = "eeee"') }),
      key({ 'Cargo.lock': LOCK.replace('checksum = "bbbb"', 'checksum = "ffff"') }),
      key({ 'Cargo.toml': MANIFEST.replace('png = "0.17"', 'png = "0.18"') }),
      key({ 'Cargo.toml': MANIFEST.replace('lto = true', 'lto = false') }),
      key({ 'rust-toolchain.toml': '[toolchain]\nchannel = "1.95.0"\n' }),
      key({ 'nix/tools.nix': '{ wasm-pack = "0.15.1"; }\n' }),
      key({}, { CARGO_PROFILE_ENGINE_WASM_LTO: 'off' }),
      wasmCacheKey(workspace(BASE_FILES), 'engine', [...BUILD, '--target', 'web'], {}),
    ];
    for (const other of changed) expect(other).not.toBe(base);
  });

  it('gives every checkout of the same sources one key', () => {
    const first = workspace(BASE_FILES);
    const second = workspace(BASE_FILES);
    const build = (root: string) => [
      ...BUILD,
      '--out-dir',
      join(root, 'apps/web/src/lib/engine/wasm'),
    ];
    expect(wasmCacheKey(first, 'engine', build(first), {})).toBe(
      wasmCacheKey(second, 'engine', build(second), {})
    );
  });
});

describe('the closure map', () => {
  it('has a wasm closure for every package the justfile builds', () => {
    const repo = resolve(import.meta.dirname, '../../..');
    const justfile = readFileSync(join(repo, 'apps/web/justfile'), 'utf8');
    // Every recipe line that runs the script; comments name it too.
    const runs = justfile
      .split('\n')
      .filter(
        (line) =>
          line.includes('cached-wasm-build.sh') &&
          !line.trimStart().startsWith('#')
      );
    const { wasm_closures } = JSON.parse(
      readFileSync(join(repo, '.github/workspace-dep-closures.json'), 'utf8')
    ) as { wasm_closures: Record<string, string[]> };

    expect(runs.length).toBeGreaterThan(0);
    for (const line of runs) {
      const name = /^[ \t]+scripts\/cached-wasm-build\.sh (\S+) /.exec(
        line
      )?.[1];
      expect(name, line).toBeDefined();
      expect(wasm_closures[name ?? '']?.length ?? 0, name).toBeGreaterThan(0);
    }
  });
});
