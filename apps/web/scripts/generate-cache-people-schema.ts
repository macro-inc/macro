import $RefParser from '@apidevtools/json-schema-ref-parser';
import { $ } from 'bun';
import { jsonSchemaToZod, parseSchema } from 'json-schema-to-zod';
import { resolve } from 'node:path';
import { z } from 'zod';

const ROOT = resolve(import.meta.dirname, '../../..');
const SOURCE = resolve(ROOT, 'crates/client/cache-core/src/people/schema.json');
const OUTPUT = resolve(import.meta.dirname, '../src/lib/graphql-cache/people/generated.ts');
const DOCUMENT = z.object({
  policyVersion: z.number().int().positive(),
  maxBatch: z.number().int().positive(),
  maxQueryBytes: z.number().int().positive(),
  schemas: z.record(z.string(), z.record(z.string(), z.unknown())),
});

if (process.argv.includes('--rust')) {
  const json = await $`cargo run --quiet -p cache-core --features schema --example people_schema`.cwd(ROOT).text();
  if (process.argv.includes('--check')) {
    if (json !== await Bun.file(SOURCE).text()) throw new Error('Rust person schemas are stale');
  } else await Bun.write(SOURCE, json);
}
const document = DOCUMENT.parse(await Bun.file(SOURCE).json());
const parts = ['// Generated by scripts/generate-cache-people-schema.ts. Do not edit.', "import { z } from 'zod/v3';", `export const PEOPLE_POLICY_VERSION = ${document.policyVersion};`, `export const MAX_PEOPLE_BATCH = ${document.maxBatch};`, `export const MAX_PEOPLE_QUERY_BYTES = ${document.maxQueryBytes};`];
for (const [name, schema] of Object.entries(document.schemas)) {
  const resolved = await $RefParser.dereference(structuredClone(schema));
  parts.push(jsonSchemaToZod(resolved, {
    module: 'esm', name: `${name}Schema`, noImport: true, withoutDescribes: true,
    parserOverride: (node, refs) => {
      if (!node.oneOf) return;
      // The generic generator erases oneOf to z.any(). Our Rust enums have
      // disjoint literal tags, so a typed union has identical validation.
      const tags = node.oneOf.map((variant) => {
        if (typeof variant === 'boolean') throw new Error('Unexpected enum variant');
        const kind = variant.properties?.kind;
        return variant.const ?? (typeof kind === 'object' ? kind.const : undefined);
      });
      if (!tags.every((tag) => typeof tag === 'string') || new Set(tags).size !== tags.length)
        throw new Error('Person protocol oneOf must have disjoint literal tags');
      return `z.union([${node.oneOf.map((variant, index) => parseSchema(variant, { ...refs, path: [...refs.path, 'oneOf', index] })).join(',')}])`;
    },
  }));
  parts.push(`export type ${name} = z.infer<typeof ${name}Schema>;`);
}
const input = Buffer.from(parts.join('\n\n'));
const output = await $`${process.env.BIOME_BINARY ?? 'biome'} format --stdin-file-path=${OUTPUT} < ${input}`.cwd(resolve(ROOT, 'apps/web')).text();
if (process.argv.includes('--check')) {
  if (await Bun.file(OUTPUT).text() !== output) throw new Error('Generated person transport is stale');
} else await Bun.write(OUTPUT, output);
