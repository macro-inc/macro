type HeadlessEntry = {
  name: string;
  seed: SerializedEditorState;
  ops: DocumentOp[];
  state: SerializedEditorState;
  failedAt: number | null;
  /** Block corpus only: refs the ops minted, kept verbatim. */
  refs?: string[];
};

type Replayed = {
  name: string;
  seed: SerializedEditorState;
  ops: DocumentOp[];
  state: SerializedEditorState;
  refused: number[];
  refs: string[];
};

type AppEntry = {
  name: string;
  /** The stored document: the app editor's first load of the headless seed. */
  seed: SerializedEditorState;
  /** The app editor's load of `seed`, the state the ops apply to. */
  loaded: SerializedEditorState;
  ops: DocumentOp[];
  state: SerializedEditorState;
  /** Ops Source reported to telemetry and skipped; later ops still applied. */
  refused: number[];
  refs: string[];
  /** Source's own load of `state`, only where it differs from `state`. */
  reloaded?: SerializedEditorState;
};

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };

/** Leaf paths where `from` and `to` differ, child arrays compared by index. */
function diff(from: Json, to: Json, path: string, out: string[]): void {
  if (Array.isArray(from) && Array.isArray(to)) {
    if (from.length !== to.length)
      out.push(`${path}: length ${from.length} -> ${to.length}`);
    for (let i = 0; i < Math.min(from.length, to.length); i++)
      diff(from[i] ?? null, to[i] ?? null, `${path}[${i}]`, out);
    return;
  }
  if (
    from !== null &&
    to !== null &&
    typeof from === 'object' &&
    typeof to === 'object' &&
    !Array.isArray(from) &&
    !Array.isArray(to)
  ) {
    for (const key of new Set([...Object.keys(from), ...Object.keys(to)])) {
      if (!(key in to)) out.push(`${path}.${key}: headless-only`);
      else if (!(key in from))
        out.push(`${path}.${key}: app-only ${JSON.stringify(to[key])}`);
      else diff(from[key] ?? null, to[key] ?? null, `${path}.${key}`, out);
    }
    return;
  }
  if (JSON.stringify(from) !== JSON.stringify(to))
    out.push(`${path}: ${JSON.stringify(from)} -> ${JSON.stringify(to)}`);
}

function visitIds(value: unknown, visit: (id: string) => void): void {
  if (Array.isArray(value)) for (const child of value) visitIds(child, visit);
  else if (value && typeof value === 'object')
    for (const [key, child] of Object.entries(value)) {
      if (key === '$' && child && typeof child === 'object') {
        const id = (child as { id?: unknown }).id;
        if (typeof id === 'string') visit(id);
      } else visitIds(child, visit);
    }
}

function renameIds(value: unknown, rename: (id: string) => string): unknown {
  if (Array.isArray(value)) return value.map((v) => renameIds(v, rename));
  if (!value || typeof value !== 'object') return value;
  const out: Record<string, unknown> = {};
  for (const [key, child] of Object.entries(value)) {
    if (key === '$' && child && typeof child === 'object') {
      const node = { ...(child as Record<string, unknown>) };
      if (typeof node.id === 'string') node.id = rename(node.id);
      out[key] = node;
    } else out[key] = renameIds(child, rename);
  }
  return out;
}

/** Serialized as stored: keys whose value is undefined are dropped. */
function stored(state: SerializedEditorState): SerializedEditorState {
  return JSON.parse(JSON.stringify(state));
}

async function settle(): Promise<void> {
  await new Promise((r) => setTimeout(r, 0));
}

async function replay(entry: HeadlessEntry): Promise<Replayed> {
  return createRoot(async (dispose) => {
    const wrapper = createLexicalWrapper({
      type: 'markdown-sync',
      namespace: 'ai-edit-app-corpus',
      isInteractable: () => true,
      withIds: true,
    });
    if (!isWrapperWithIds(wrapper)) throw new Error('expected node ids');
    const { editor, plugins, mapping } = wrapper;
    try {
      editor.setRootElement(document.createElement('div'));
      plugins.richText().list().markdownShortcuts().delete().history(400);
      registerMarkdownEditing({
        lexicalWrapper: wrapper,
        isContentEditable: () => true,
        peerIdValidator: () => true,
        source: { id: 'corpus', trackMentions: false },
        onVersionError: (error) => {
          throw new Error(`version error ${error}`);
        },
      });
      editor.setEditorState(editor.parseEditorState(entry.seed));
      // A loaded document's nodes are all new to the editor, so node
      // transforms run on every one of them; marking each writable does that.
      editor.update(
        () => {
          const touch = (node: LexicalNode) => {
            node.getWritable();
            if ($isElementNode(node)) node.getChildren().forEach(touch);
          };
          touch($getRoot());
          $updateAllNodeIds(mapping);
        },
        { discrete: true }
      );
      await settle();
      const seed = stored(editor.getEditorState().toJSON());
      // Attribute each telemetry report to the op being applied.
      let current = -1;
      const refused: number[] = [];
      const apply = Doc.prototype.apply;
      const applySpy = vi
        .spyOn(Doc.prototype, 'apply')
        .mockImplementation(function (this: Doc, op: DocumentOp) {
          current++;
          apply.call(this, op);
        });
      const reportSpy = vi.spyOn(Telemetry, 'error').mockImplementation(() => {
        if (current >= 0 && !refused.includes(current)) refused.push(current);
      });
      try {
        applyAiOps(editor, mapping, entry.ops);
      } finally {
        applySpy.mockRestore();
        reportSpy.mockRestore();
      }
      await settle();
      const state = stored(editor.getEditorState().toJSON());
      // Seed ids keep the headless names; ids the load minted continue them;
      // refs stay verbatim; ids the ops minted are <newN> in document order.
      const names = new Map<string, string>();
      visitIds(entry.seed, (id) => names.set(id, id));
      const refs = entry.refs ?? [];
      for (const ref of refs) names.set(ref, ref);
      let loaded = names.size - refs.length;
      visitIds(seed, (id) => {
        if (!names.has(id))
          names.set(id, `s${String(loaded++).padStart(7, '0')}`);
      });
      let minted = 0;
      const rename = (id: string) => {
        let name = names.get(id);
        if (name === undefined) {
          name = `<new${minted++}>`;
          names.set(id, name);
        }
        return name;
      };
      return {
        name: entry.name,
        seed: renameIds(seed, rename) as SerializedEditorState,
        ops: entry.ops,
        state: renameIds(state, rename) as SerializedEditorState,
        refused,
        refs,
      };
    } finally {
      wrapper.cleanup();
      dispose();
    }
  });
}

type Deltas = Record<
  string,
  {
    seed: string[];
    state: string[];
    /** Set when the app refuses different ops than the headless Doc. */
    refused?: { headless: number[]; app: number[] };
  }
>;

/** The headless text corpus marks every minted id `<new>`; compare in its terms. */
function oneBucket(value: unknown): unknown {
  return renameIds(value, (id) => (/^<new\d+>$/.test(id) ? '<new>' : id));
}

/** Regenerate one corpus's app profile and return its named headless->app aspect. */
async function generate(
  headlessName: string,
  appName: string
): Promise<Deltas> {
  const appPath = resolve(CORPUS_DIR, appName);
  const headless = JSON.parse(
    readFileSync(resolve(CORPUS_DIR, headlessName), 'utf8')
  ) as HeadlessEntry[];
  const app: AppEntry[] = [];
  for (const entry of headless) {
    // Stored once, then loaded again as the native replay will load it.
    const stored = await replay({ ...entry, ops: [] });
    const run = await replay({ ...entry, seed: stored.seed });
    // Loading the resulting state again: recorded only where it changes.
    const again = await replay({ ...entry, seed: run.state, ops: [] });
    app.push({
      name: entry.name,
      seed: stored.seed,
      loaded: run.seed,
      ops: entry.ops,
      state: run.state,
      refused: run.refused,
      refs: run.refs,
      ...(JSON.stringify(again.seed) === JSON.stringify(run.state)
        ? {}
        : { reloaded: again.seed }),
    });
  }
  const json = `${JSON.stringify(app, null, 2)}\n`;
  if (process.env.UPDATE_NATIVE_CORPUS === '1') writeFileSync(appPath, json);
  expect(existsSync(appPath)).toBe(true);
  expect(readFileSync(appPath, 'utf8')).toBe(json);
  const bucketed = headless.some((entry) =>
    JSON.stringify(entry.state).includes('"<new>"')
  );
  const deltas: Deltas = {};
  for (const [index, entry] of headless.entries()) {
    const target = app[index];
    if (!target) throw new Error(`missing ${entry.name}`);
    // Source reports the op the headless Doc stopped at, then carries on.
    const headlessRefused = entry.failedAt === null ? [] : [entry.failedAt];
    const view = (value: unknown) =>
      (bucketed ? oneBucket(value) : value) as Json;
    const seed: string[] = [];
    diff(entry.seed as never, view(target.seed), '', seed);
    const state: string[] = [];
    diff(entry.state as never, view(target.state), '', state);
    deltas[entry.name] =
      JSON.stringify(target.refused) === JSON.stringify(headlessRefused)
        ? { seed, state }
        : {
            seed,
            state,
            refused: { headless: headlessRefused, app: target.refused },
          };
  }
  return deltas;
}

// documentMetadataPlugin stamps the version on the first load; loading that
// stored state parses it, which adds environmentTags: null.
const STORED_METADATA = '.root.$.documentMetadata: app-only {"version":11}';
const LOADED_METADATA =
  '.root.$.documentMetadata: app-only {"version":11,"environmentTags":null}';

/** Every seed and state gains documentMetadata; returns the other state deltas. */
/** Cases where the app refuses different ops than the headless Doc. */
function refusalDifferences(deltas: Deltas) {
  return Object.fromEntries(
    Object.entries(deltas).flatMap(([name, { refused }]) =>
      refused ? [[name, refused]] : []
    )
  );
}

function beyondMetadata(deltas: Deltas): Record<string, string[]> {
  for (const { seed, state } of Object.values(deltas)) {
    expect(seed).toEqual([STORED_METADATA]);
    expect(state).toContain(LOADED_METADATA);
  }
  return Object.fromEntries(
    Object.entries(deltas)
      .map(([name, { state }]) => [
        name,
        state.filter((d) => d !== LOADED_METADATA),
      ])
      .filter(([, rest]) => rest.length > 0)
  );
}

test('the native text-op corpus is the app Source profile of the headless cases', async () => {
  const deltas = await generate('text.json', 'text.app.json');
  const out = process.env.AI_EDIT_APP_PROFILE_TEXT_OUT;
  if (out) writeFileSync(out, `${JSON.stringify(deltas, null, 2)}\n`);
  expect(refusalDifferences(deltas)).toEqual({});
  expect(beyondMetadata(deltas)).toEqual({
    // The op after the refused one applies.
    'a missed replaceText keeps the earlier op and stops': [
      '.root.children[1].children[0].text: "Beta" -> "never applied"',
    ],
  });
});

test('the native block-op corpus is the app Source profile of the headless cases', async () => {
  const deltas = await generate('blocks.json', 'blocks.app.json');
  const out = process.env.AI_EDIT_APP_PROFILE_OUT;
  if (out) writeFileSync(out, `${JSON.stringify(deltas, null, 2)}\n`);
  expect(beyondMetadata(deltas)).toEqual({
    'insertNode table with a header row': [
      '.root.children: length 2 -> 3',
      '.root.children[1].colWidths: app-only [120,120]',
    ],
    'insertNode table with all-empty cells': [
      '.root.children: length 2 -> 3',
      '.root.children[1].colWidths: app-only [120,120]',
    ],
    'setBlockType paragraph to code with a language': [
      '.root.children: length 1 -> 2',
    ],
    // The op after the refused one applies: the seed block is removed.
    'a failing removeNode keeps the earlier insert and stops': [
      '.root.children: length 2 -> 1',
      '.root.children[0].children[0].text: "Alpha" -> "kept"',
      '.root.children[0].children[0].$.id: "s0000000" -> "<new0>"',
      '.root.children[0].$.id: "s0000001" -> "ref-kept"',
    ],
    // The app's nodeIdPlugin drops a retyped block's old id when the retype
    // commits (its destroyed-node cleanup), so a later op cannot address it.
    'setBlockType then address the old id': [
      '.root.children[0].children[0].text: "Alpha more" -> "Alpha"',
    ],
    'setBlockType twice through the old id': [
      '.root.children[0].type: "quote" -> "heading"',
      '.root.children[0].tag: app-only "h2"',
    ],
  });
  expect(refusalDifferences(deltas)).toEqual({
    'setBlockType then address the old id': { headless: [], app: [1] },
    'setBlockType twice through the old id': { headless: [], app: [1] },
  });
});

test('the app Source editor loads its oracle states as recorded', async () => {
  // The native import is held to `loaded`: Source's own load of the stored
  // seed. Loading `loaded` or `state` again changes nothing further.
  const changed: string[] = [];
  for (const name of ['text.app.json', 'blocks.app.json']) {
    const app = JSON.parse(
      readFileSync(resolve(CORPUS_DIR, name), 'utf8')
    ) as AppEntry[];
    for (const entry of app)
      for (const [label, from, expected] of [
        ['seed', entry.seed, entry.loaded],
        ['loaded', entry.loaded, entry.loaded],
        ['state', entry.state, entry.reloaded ?? entry.state],
      ] as const) {
        const reloaded = await replay({
          name: entry.name,
          seed: from,
          ops: [],
          state: from,
          failedAt: null,
          refs: entry.refs,
        });
        const deltas: string[] = [];
        diff(expected as never, reloaded.seed as never, '', deltas);
        if (deltas.length > 0)
          changed.push(
            `${name} ${entry.name} [${label}]: ${deltas.join('; ')}`
          );
      }
  }
  expect(changed).toEqual([]);
  // One Source state the app editor itself does not keep: a paragraph placed
  // before a list item stays a direct child of the list (LexicalNode
  // insertBefore links it without the list's splice), and only a reload's
  // transforms wrap it in a list item. Native targets the state as left and,
  // on load, Source's reload of it.
  const unstable = ['text.app.json', 'blocks.app.json'].flatMap((name) =>
    (JSON.parse(readFileSync(resolve(CORPUS_DIR, name), 'utf8')) as AppEntry[])
      .filter((entry) => entry.reloaded)
      .map((entry) => entry.name)
  );
  expect(unstable).toEqual(['insertNode paragraph before a list item']);
});
