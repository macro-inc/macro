// The native block-op oracle, generated by the app's Source editor: the same
// wrapper, base plugins and registerMarkdownEditing composition as
// block-md MarkdownEditor, replaying each case of the worker's headless
// corpora (text.json and blocks.json: seed and ops) through the real
// applyAiOps. Writes corpus/text.app.json and corpus/blocks.app.json, the
// single native targets: `seed` as first stored, `loaded` as the app editor
// loads it, and `state` after the ops from `loaded`. The app editor's onError is
// Telemetry.error, so a refused op is dropped and later ops still apply
// (live-20261113/live-refusal.json); `refused` lists the op indices Source
// reported and skipped. Regenerate with
// UPDATE_NATIVE_CORPUS=1. Live-app confirmation of the profile: live OFF
// capture 2a10869b (documentMetadata, colWidths, trailing paragraph).
//
// Left out of MarkdownEditor's composition, none of which writes node state
// on load or on an AI op:
// - history(400, loroManager): Loro history records undo only; the lexical
//   history used here (no manager) records the same commits.
// - state(setState, 'json'): mirrors the state into a signal.
// - locationPlugin and the document slots (tags, find and replace, pinned
//   properties, diff, AI generate): menus, search decorations and
//   flag-gated features driven by user input, not by load or applyAiOps.
// - CollabProvider: the sync transport; the load below stands in for its
//   initial reconcile.

