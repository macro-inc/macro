export function isPreset(value: unknown): value is PresetId {
  return typeof value === 'string' && Object.hasOwn(presets, value);
}

export function isPortraitTab(value: unknown): value is PortraitTab {
  return typeof value === 'string' && Object.hasOwn(portraitTabs, value);
}

export function optionLabel(
  options: readonly (readonly [string, string, ...string[]])[],
  value: string
) {
  return options.find(([id]) => id === value)?.[1];
}
