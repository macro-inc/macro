type ChoiceKey = keyof typeof choices;
type RangeKey = keyof typeof ranges;
export type Look = {
  [K in ChoiceKey]: (typeof choices)[K][number][0];
} & Record<RangeKey, number>;

type TabControl =
  | { key: ChoiceKey; label: string; columns: number }
  | { key: RangeKey; label: string; columns?: never };

export function isLook(value: unknown): value is Look {
  if (!value || typeof value !== 'object') return false;

  return (
    Object.entries(choices).every(([key, options]) =>
      options.some(
        ([option]) =>
          Object.getOwnPropertyDescriptor(value, key)?.value === option
      )
    ) &&
    Object.entries(ranges).every(([key, { min, max }]) => {
      const current: unknown = Object.getOwnPropertyDescriptor(
        value,
        key
      )?.value;
      return (
        typeof current === 'number' &&
        Number.isFinite(current) &&
        current >= min &&
        current <= max
      );
    })
  );
}

