"""Compile drawn glyphs into OpenType fonts (CFF .otf, TrueType .ttf, .woff2)."""

from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from fontTools.fontBuilder import FontBuilder
from fontTools.misc.timeTools import timestampFromString
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.pens.ttGlyphPen import TTGlyphPen

from . import params as P
from .glyphs import REGISTRY


class _RoundPen:
    """Rounds coordinates to integers before passing them on, dropping
    segments that rounding collapses to a point."""

    def __init__(self, pen):
        self.pen = pen
        self.cur = None

    @staticmethod
    def _r(pt):
        return (round(pt[0]), round(pt[1]))

    def moveTo(self, pt):
        self.cur = self._r(pt)
        self.pen.moveTo(self.cur)

    def lineTo(self, pt):
        pt = self._r(pt)
        if pt != self.cur:
            self.pen.lineTo(pt)
            self.cur = pt

    def curveTo(self, *pts):
        pts = [self._r(p) for p in pts]
        if any(p != self.cur for p in pts):
            self.pen.curveTo(*pts)
            self.cur = pts[-1]

    def qCurveTo(self, *pts):
        self.pen.qCurveTo(*[self._r(p) if p is not None else None for p in pts])

    def closePath(self):
        self.pen.closePath()

    def endPath(self):
        self.pen.endPath()


def _names(p, variable=False):
    style = P.WEIGHTS.get(p.wght, str(p.wght)) if not variable else "Regular"
    ribbi = style in ("Regular", "Bold")
    family = P.FAMILY if (ribbi or variable) else f"{P.FAMILY} {style}"
    ps_style = style.replace(" ", "")
    ps = f"{P.PS_FAMILY}-{ps_style}" if not variable else f"{P.PS_FAMILY}-Variable"
    names = {
        "copyright": "Copyright 2026 Macro. Generated by tooling/fonts/kernel-sans.",
        "familyName": family if not variable else f"{P.FAMILY} Variable",
        "styleName": style if ribbi else "Regular",
        "uniqueFontIdentifier": f"{P.VERSION};MCRO;{ps}",
        "fullName": f"{P.FAMILY} {style}" if not variable else f"{P.FAMILY} Variable",
        "psName": ps,
        "version": f"Version {P.VERSION}",
        "manufacturer": "Macro",
        "description": "A neo-grotesque sans with squircle bowls, 45-degree chamfered terminals and ink traps.",
    }
    if not ribbi and not variable:
        names["typographicFamily"] = P.FAMILY
        names["typographicSubfamily"] = style
    return names


def _cmap():
    cmap = {}
    for d in REGISTRY.values():
        for u in d.unicodes:
            cmap[u] = d.name
    return cmap


def build_font(drawn, p, fmt="otf", features=None):
    """drawn: {glyph name: G} for weight params p. fmt: "otf" (CFF) or "ttf"."""
    order = list(drawn)
    assert order[0] == ".notdef", "glyph order must start with .notdef"
    is_ttf = fmt == "ttf"
    fb = FontBuilder(P.UPM, isTTF=is_ttf)
    fb.setupGlyphOrder(order)
    cmap = {u: n for u, n in _cmap().items() if n in drawn}
    fb.setupCharacterMap(cmap)

    metrics = {}
    if is_ttf:
        glyphs = {}
        for name, g in drawn.items():
            pen = TTGlyphPen(None)
            # pathops gives counter-clockwise outer contours (PostScript
            # direction); TrueType wants clockwise, so reverse while
            # converting cubics to quadratics.
            g.shape.path.draw(
                _RoundPen(Cu2QuPen(pen, max_err=1.0, reverse_direction=True))
            )
            glyphs[name] = pen.glyph()
        fb.setupGlyf(glyphs)
        glyf = fb.font["glyf"]
        for name, g in drawn.items():
            gl = glyf[name]
            gl.recalcBounds(glyf)
            metrics[name] = (
                round(g.width),
                getattr(gl, "xMin", 0) if gl.numberOfContours else 0,
            )
    else:
        charstrings = {}
        for name, g in drawn.items():
            pen = T2CharStringPen(round(g.width), None)
            g.shape.path.draw(_RoundPen(pen))
            charstrings[name] = pen.getCharString()
            bp = BoundsPen(None)
            g.shape.path.draw(_RoundPen(bp))
            metrics[name] = (round(g.width), bp.bounds[0] if bp.bounds else 0)
        names = _names(p)
        fb.setupCFF(
            names["psName"],
            {"FullName": names["fullName"], "FamilyName": P.FAMILY, "Weight": p.name},
            charstrings,
            {
                "BlueValues": [-P.OS, 0, P.XH, P.XH + P.OS, P.CAP, P.CAP + P.COS],
                "StdHW": round(p.hair),
                "StdVW": round(p.stem),
            },
        )

    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=P.HHEA_ASC, descent=P.HHEA_DESC)
    # Windows records only: Mac records would be copied unchanged into the
    # variable font, which renames only the Windows ones.
    fb.setupNameTable(_names(p), mac=False)
    style = P.WEIGHTS.get(p.wght, "")
    # Every weight but Bold is the Regular of its own family (nameID 2).
    fs_selection = 0x20 if style == "Bold" else 0x40
    fs_selection |= 0x80  # USE_TYPO_METRICS
    # Strikeout follows the hyphen; sub- and superscript sizes are the usual
    # 65/60% of the em.
    hy = drawn["hyphen"].shape.bounds() if "hyphen" in drawn else None
    fb.setupOS2(
        version=4,
        usWeightClass=p.wght,
        usWidthClass=5,
        fsType=0,
        sTypoAscender=P.HHEA_ASC,
        sTypoDescender=P.HHEA_DESC,
        sTypoLineGap=0,
        usWinAscent=max(P.HHEA_ASC, 1000),
        usWinDescent=max(-P.HHEA_DESC, 300),
        sxHeight=P.XH,
        sCapHeight=P.CAP,
        achVendID="MCRO",
        fsSelection=fs_selection,
        ulCodePageRange1=0b1,  # Latin 1
        yStrikeoutSize=round(hy[3] - hy[1]) if hy else round(p.hair),
        yStrikeoutPosition=round(hy[3]) if hy else P.AXIS,
        ySubscriptXSize=650,
        ySubscriptYSize=600,
        ySubscriptYOffset=75,
        ySuperscriptXSize=650,
        ySuperscriptYSize=600,
        ySuperscriptYOffset=350,
    )
    # Unicode ranges from the cmap (passing any ulUnicodeRange field to
    # setupOS2 turns its own calculation off).
    fb.font["OS/2"].recalcUnicodeRanges(fb.font)
    fb.setupPost(
        isFixedPitch=0, underlinePosition=-110, underlineThickness=round(p.hair * 0.8)
    )
    fb.font["head"].macStyle = 0x01 if style == "Bold" else 0
    if features:
        addOpenTypeFeaturesFromString(fb.font, features)
    pin_timestamps(fb.font)
    return fb.font


def pin_timestamps(font):
    stamp = timestampFromString(P.BUILD_DATE)
    font["head"].created = font["head"].modified = stamp
    font.recalcTimestamp = False


def to_woff2(font, path):
    font.flavor = "woff2"
    font.save(path)
    font.flavor = None
