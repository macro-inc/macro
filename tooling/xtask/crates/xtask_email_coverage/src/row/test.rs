use super::{Kind, Providers, Row, diff, parse_tsv, render_tsv};

fn route(key: &str, source: &str) -> Row {
    Row {
        kind: Kind::Http,
        key: key.to_owned(),
        providers: Providers::Both,
        matcher: String::new(),
        source: source.to_owned(),
    }
}

#[test]
fn check_reports_rows_only_in_the_file_and_only_in_the_code() {
    let checked_in = [
        route("GET /health", "api/health.rs:18"),
        route("GET /old", "api/old.rs:4"),
        route("POST /init", "api/email.rs:41"),
    ];
    let generated = [
        route("GET /health", "api/health.rs:18"),
        route("POST /init", "api/email.rs:44"),
        route("PUT /new", "api/new.rs:9"),
    ];

    assert_eq!(
        diff(&checked_in, &generated),
        // A route that only moved within its file is the same entry point.
        [
            "- http\tGET /old\tboth\t\tapi/old.rs",
            "+ http\tPUT /new\tboth\t\tapi/new.rs",
        ]
    );
    assert_eq!(diff(&checked_in, &checked_in), Vec::<String>::new());
}

#[test]
fn the_written_file_reads_back_as_the_same_rows() {
    let rows = [
        Row {
            kind: Kind::Queue,
            key: "gmail-ops:DeleteLabel".to_owned(),
            providers: Providers::Gmail,
            matcher: "/operation/delete_label".to_owned(),
            source: "crates/models_email/src/gmail/gmail_ops.rs:28".to_owned(),
        },
        route("GET /health", "api/health.rs:18"),
    ];

    let text = render_tsv(&rows);

    assert_eq!(
        text,
        "# Generated by cargo run -p xtask -- email-coverage list. Do not edit.\n\
         kind\tkey\tproviders\tmatch\tsource\n\
         queue\tgmail-ops:DeleteLabel\tgmail\t/operation/delete_label\tcrates/models_email/src/gmail/gmail_ops.rs:28\n\
         http\tGET /health\tboth\t\tapi/health.rs:18\n"
    );
    assert_eq!(parse_tsv(&text, "entrypoints.tsv").unwrap(), rows);
}

#[test]
fn a_row_with_an_unknown_kind_is_refused_with_its_line() {
    let text = "kind\tkey\tproviders\tmatch\tsource\nsocket\tx\tboth\t\ta.rs:1\n";

    let error = parse_tsv(text, "entrypoints.tsv").unwrap_err();

    assert!(
        error
            .to_string()
            .contains("entrypoints.tsv:2: unknown kind `socket`"),
        "{error}"
    );
}
