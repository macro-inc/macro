// Markers for the Darwin node_modules check in Namespace's remote cache, one per
// derivation that passed it. `MARKER_MODE` picks the step:
//
//   lookup  before the check, on Linux: write `passed=true` to the step outputs
//           when a marker for `DRV` exists
//   record  after the check passed: leave the marker for `DRV`
//
// A failed lookup reads as "not passed", so the check runs; a failed record
// costs the next run a check, so neither fails the job.

import { execFileSync } from 'node:child_process';
import { appendFileSync } from 'node:fs';

const PREFIX = 'node-modules-verified';

export type Credentials = { endpoint: string; token: string };

/** Parse the `KEY=value` lines `nsc cache sccache setup` prints. */
export function parseCredentials(output: string): Credentials | undefined {
  const values = new Map<string, string>();
  for (const line of output.split('\n')) {
    const separator = line.indexOf('=');
    if (separator > 0) values.set(line.slice(0, separator), line.slice(separator + 1).trim());
  }
  const endpoint = values.get('SCCACHE_WEBDAV_ENDPOINT');
  const token = values.get('SCCACHE_WEBDAV_TOKEN');
  return endpoint && token ? { endpoint, token } : undefined;
}

/** The marker's URL. `drv` is a store path's base name, such as `abc-x.drv`. */
export function markerUrl(endpoint: string, drv: string): string {
  if (!/^[0-9a-z]{32}-[A-Za-z0-9+._?=-]+\.drv$/.test(drv))
    throw new Error(`not a derivation name: ${JSON.stringify(drv)}`);
  return `${endpoint.replace(/\/+$/, '')}/${PREFIX}/${drv}`;
}

function credentials(cacheName: string): Credentials | undefined {
  try {
    const output = execFileSync('nsc', ['cache', 'sccache', 'setup', '--cache_name', cacheName], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'inherit'],
    });
    const parsed = parseCredentials(output);
    if (parsed) console.log(`::add-mask::${parsed.token}`);
    return parsed;
  } catch (error) {
    console.log(`::warning::No remote cache credentials: ${String(error)}`);
    return undefined;
  }
}

export async function lookup(
  drv: string,
  creds: Credentials | undefined,
  fetcher: typeof fetch = fetch,
): Promise<boolean> {
  if (!creds) return false;
  try {
    const response = await fetcher(markerUrl(creds.endpoint, drv), {
      method: 'HEAD',
      headers: { Authorization: `Bearer ${creds.token}` },
      signal: AbortSignal.timeout(30_000),
    });
    return response.ok;
  } catch (error) {
    console.log(`::warning::Marker lookup failed: ${String(error)}`);
    return false;
  }
}

export async function record(
  drv: string,
  body: string,
  creds: Credentials | undefined,
  fetcher: typeof fetch = fetch,
): Promise<boolean> {
  if (!creds) return false;
  try {
    const response = await fetcher(markerUrl(creds.endpoint, drv), {
      method: 'PUT',
      headers: { Authorization: `Bearer ${creds.token}` },
      body,
      signal: AbortSignal.timeout(30_000),
    });
    if (!response.ok) console.log(`::warning::Could not record the check: HTTP ${response.status}`);
    return response.ok;
  } catch (error) {
    console.log(`::warning::Could not record the check: ${String(error)}`);
    return false;
  }
}

function env(name: string): string {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is required`);
  return value;
}

export async function main(): Promise<void> {
  const drv = env('DRV');
  const creds = credentials(env('CACHE_NAME'));
  switch (env('MARKER_MODE')) {
    case 'lookup': {
      const passed = await lookup(drv, creds);
      console.log(passed ? `${drv} passed the Darwin check before` : `${drv} has no passed check`);
      appendFileSync(env('GITHUB_OUTPUT'), `passed=${passed}\n`);
      return;
    }
    case 'record': {
      // A Linux evaluation that differs from macOS's would never find the marker.
      const linuxDrv = process.env.LINUX_DRV;
      if (linuxDrv && linuxDrv !== drv)
        console.log(`::warning::Linux evaluated ${linuxDrv}, macOS built ${drv}; lookups will miss`);
      if (await record(drv, `${env('RUN_URL')}\n`, creds)) console.log(`Recorded ${drv}`);
      return;
    }
    default:
      throw new Error(`unknown MARKER_MODE ${process.env.MARKER_MODE}`);
  }
}
