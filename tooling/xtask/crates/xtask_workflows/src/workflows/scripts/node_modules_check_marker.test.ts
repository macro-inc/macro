import assert from 'node:assert/strict';
import { test } from 'node:test';

import { lookup, markerBody, markerUrl, parseCredentials, record } from './node_modules_check_marker.ts';

const DRV = 'q08dd819rcc6k6kg6v27bn1gc703dn2v-macro-js-node-modules-2.5.0.drv';
const VERSION = 'a'.repeat(64);
const CREDS = { endpoint: 'https://cache.example/webdav/', token: 'secret' };
const RUN = 'https://github.com/o/r/actions/runs/1';

test('parses the credentials nsc prints', () => {
  assert.deepEqual(
    parseCredentials('SCCACHE_WEBDAV_ENDPOINT=https://e/x\nSCCACHE_WEBDAV_TOKEN=t=1\nOTHER=y\n'),
    { endpoint: 'https://e/x', token: 't=1' },
  );
  assert.equal(parseCredentials('SCCACHE_WEBDAV_ENDPOINT=https://e/x\n'), undefined);
});

test('names the marker after the check version and the derivation', () => {
  assert.equal(
    markerUrl(CREDS.endpoint, VERSION, DRV),
    `https://cache.example/webdav/node-modules-verified/${VERSION}/${DRV}`,
  );
  assert.throws(() => markerUrl(CREDS.endpoint, VERSION, ''));
  assert.throws(() => markerUrl(CREDS.endpoint, VERSION, '../x.drv'));
  assert.throws(() => markerUrl(CREDS.endpoint, VERSION, `/nix/store/${DRV}`));
  assert.throws(() => markerUrl(CREDS.endpoint, '', DRV));
  assert.throws(() => markerUrl(CREDS.endpoint, '../x', DRV));
});

function fakeFetch(answer: Response | Error, calls: Request[] = []): typeof fetch {
  return (async (url: string, init: RequestInit) => {
    calls.push(new Request(url, init));
    if (answer instanceof Error) throw answer;
    return answer;
  }) as typeof fetch;
}

test('only a marker naming the derivation means passed', async () => {
  const calls: Request[] = [];
  const marker = () => new Response(markerBody(DRV, RUN));
  assert.equal(await lookup(VERSION, DRV, CREDS, fakeFetch(marker(), calls)), true);
  assert.equal(calls[0].method, 'GET');
  assert.equal(calls[0].redirect, 'error');
  assert.equal(calls[0].headers.get('authorization'), 'Bearer secret');
  // An endpoint that answers 200 with anything else is not a marker.
  assert.equal(await lookup(VERSION, DRV, CREDS, fakeFetch(new Response('<html>'))), false);
  assert.equal(await lookup(VERSION, DRV, CREDS, fakeFetch(new Response(''))), false);
  assert.equal(await lookup(VERSION, DRV, CREDS, fakeFetch(new Response(null, { status: 404 }))), false);
  assert.equal(await lookup(VERSION, DRV, CREDS, fakeFetch(new Error('reset'))), false);
  assert.equal(await lookup(VERSION, DRV, undefined, fakeFetch(marker())), false);
});

test('records the derivation with a PUT and never throws', async () => {
  const calls: Request[] = [];
  assert.equal(await record(VERSION, DRV, RUN, CREDS, fakeFetch(new Response(null, { status: 201 }), calls)), true);
  assert.equal(calls[0].method, 'PUT');
  assert.equal(await calls[0].text(), markerBody(DRV, RUN));
  assert.equal(await record(VERSION, DRV, RUN, CREDS, fakeFetch(new Response(null, { status: 500 }))), false);
  assert.equal(await record(VERSION, DRV, RUN, CREDS, fakeFetch(new Error('reset'))), false);
});
