import assert from 'node:assert/strict';
import { test } from 'node:test';

import { lookup, markerUrl, parseCredentials, record } from './node_modules_check_marker.ts';

const DRV = 'q08dd819rcc6k6kg6v27bn1gc703dn2v-macro-js-node-modules-2.5.0.drv';
const CREDS = { endpoint: 'https://cache.example/webdav/', token: 'secret' };

test('parses the credentials nsc prints', () => {
  assert.deepEqual(
    parseCredentials('SCCACHE_WEBDAV_ENDPOINT=https://e/x\nSCCACHE_WEBDAV_TOKEN=t=1\nOTHER=y\n'),
    { endpoint: 'https://e/x', token: 't=1' },
  );
  assert.equal(parseCredentials('SCCACHE_WEBDAV_ENDPOINT=https://e/x\n'), undefined);
});

test('names the marker after the derivation', () => {
  assert.equal(markerUrl(CREDS.endpoint, DRV), `https://cache.example/webdav/node-modules-verified/${DRV}`);
  assert.throws(() => markerUrl(CREDS.endpoint, ''));
  assert.throws(() => markerUrl(CREDS.endpoint, '../x.drv'));
  assert.throws(() => markerUrl(CREDS.endpoint, `/nix/store/${DRV}`));
});

function fakeFetch(status: number | Error, calls: Request[] = []): typeof fetch {
  return (async (url: string, init: RequestInit) => {
    calls.push(new Request(url, init));
    if (status instanceof Error) throw status;
    return new Response(null, { status });
  }) as typeof fetch;
}

test('a marker means passed; anything else means run the check', async () => {
  const calls: Request[] = [];
  assert.equal(await lookup(DRV, CREDS, fakeFetch(200, calls)), true);
  assert.equal(calls[0].method, 'HEAD');
  assert.equal(calls[0].headers.get('authorization'), 'Bearer secret');
  assert.equal(await lookup(DRV, CREDS, fakeFetch(404)), false);
  assert.equal(await lookup(DRV, CREDS, fakeFetch(new Error('reset'))), false);
  assert.equal(await lookup(DRV, undefined, fakeFetch(200)), false);
});

test('records with a PUT and never throws', async () => {
  const calls: Request[] = [];
  assert.equal(await record(DRV, 'run\n', CREDS, fakeFetch(201, calls)), true);
  assert.equal(calls[0].method, 'PUT');
  assert.equal(await calls[0].text(), 'run\n');
  assert.equal(await record(DRV, 'run\n', CREDS, fakeFetch(500)), false);
  assert.equal(await record(DRV, 'run\n', CREDS, fakeFetch(new Error('reset'))), false);
});
