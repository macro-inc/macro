// Which advisories fail a PR. Run by xtask_workflows' tests.

import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import { addedByPr, type Diagnostic, errors, lockedPackages } from './cargo_deny_new_advisories.ts';

const LOCKFILE = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "ammonia"
version = "4.1.8"
source = "registry+https://github.com/rust-lang/crates.io-index"
dependencies = [
 "html5ever",
]

[[package]]
name = "html5ever"
version = "0.35.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
`;

// cargo-deny 0.19.8's line for RUSTSEC-2026-0533, cut to the fields read.
const AMMONIA =
  '{"type":"diagnostic","fields":{"severity":"error","code":"vulnerability",' +
  '"message":"Incorrect handling of embedded SVG and MathML leads to mutation XSS",' +
  '"advisory":{"id":"RUSTSEC-2026-0533"},' +
  '"graphs":[{"Krate":{"name":"ammonia","version":"4.1.8"},"parents":[]}]}}';

const YANKED =
  '{"type":"diagnostic","fields":{"severity":"warning","code":"yanked",' +
  '"message":"detected yanked crate","graphs":[{"Krate":{"name":"chacha20","version":"0.9.0"}}]}}';

const SUMMARY = '{"type":"summary","fields":{"advisories":{"errors":1,"helps":0,"notes":0,"warnings":1}}}';

const vulnerability = (name: string, version: string): Diagnostic => ({
  severity: 'error',
  code: 'vulnerability',
  message: 'm',
  advisory: { id: 'RUSTSEC-0000-0000' },
  graphs: [{ Krate: { name, version } }],
});

describe('lockedPackages', () => {
  test('reads each package name and version', () => {
    assert.deepEqual(lockedPackages(LOCKFILE), new Set(['ammonia@4.1.8', 'html5ever@0.35.0']));
  });
});

describe('errors', () => {
  test('keeps errors and skips warnings, summaries and plain lines', () => {
    const found = errors(['plain log line', YANKED, AMMONIA, SUMMARY, ''].join('\n'));
    assert.equal(found.length, 1);
    assert.equal(found[0].advisory?.id, 'RUSTSEC-2026-0533');
  });
});

describe('addedByPr', () => {
  const base = lockedPackages(LOCKFILE);

  test('an advisory against a package the base already has does not fail the PR', () => {
    assert.equal(addedByPr(errors(AMMONIA)[0], base), false);
  });

  test('an advisory against a version the PR adds fails it', () => {
    assert.equal(addedByPr(vulnerability('ammonia', '4.1.7'), base), true);
  });

  test('an advisory against a crate the PR adds fails it', () => {
    assert.equal(addedByPr(vulnerability('evil', '1.0.0'), base), true);
  });

  test('an error that names no package fails the PR', () => {
    assert.equal(addedByPr({ severity: 'error', message: 'failed to load advisory database' }, base), true);
  });
});
