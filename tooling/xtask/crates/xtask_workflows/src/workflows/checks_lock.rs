//! `checks.lock` — every check name the generated workflows produce, the
//! commit statuses `main` requires, and the job names scripts read back.
//!
//! GitHub matches required checks and scripts match job results by name, so a
//! rename in Rust can silently drop a requirement or break a script. The lock
//! is regenerated with the workflows and checked by `--check`, so every rename
//! shows up as a reviewed diff of this file.

use std::collections::BTreeMap;
use std::fmt::Write;

use anyhow::{Context, Result, bail};
use serde_yaml::Value;

use crate::workflows::{cla, pr_ci};

/// Lock file path, relative to the repository root.
pub const PATH: &str = "tooling/xtask/crates/xtask_workflows/checks.lock";

/// The commit statuses `main`'s ruleset requires, and the workflow that posts
/// each one.
pub const REQUIRED_STATUSES: &[(&str, &str)] = &[
    (pr_ci::GATE_CONTEXT, "pr-ci.yml"),
    (cla::STATUS_CONTEXT, "cla.yml"),
];

/// Job names `ci_gate.ts` looks up in a finished `PR CI` run.
const SCRIPT_READ_JOBS: &[(&str, &str)] = &[
    ("pr-ci.yml", pr_ci::START_JOB),
    ("pr-ci.yml", pr_ci::GATE_JOB),
];

/// Render the lock from every workflow, keyed by file name. Reusable-workflow
/// calls expand into the called jobs as `<caller> / <called>`, the name GitHub
/// shows for them.
pub fn render(workflows: &BTreeMap<String, String>) -> Result<String> {
    let parsed: BTreeMap<&str, Value> = workflows
        .iter()
        .map(|(file, yaml)| {
            serde_yaml::from_str(yaml)
                .map(|value| (file.as_str(), value))
                .with_context(|| format!("parsing {file}"))
        })
        .collect::<Result<_>>()?;

    let mut lock = String::from(
        "# Generated by `cargo x workflows`; review every change. GitHub and our scripts\n\
         # match these names, so a rename here can drop a required check.\n",
    );

    for (context, file) in REQUIRED_STATUSES {
        writeln!(lock, "required-status\t{context}\t{file}")?;
    }
    for (file, job_name) in SCRIPT_READ_JOBS {
        writeln!(lock, "script-reads-job\t{file}\t{job_name}")?;
    }

    for (file, workflow) in &parsed {
        let mut checks = Vec::new();
        collect_checks(&parsed, file, workflow, "", "", &mut checks)?;
        for (job_path, check_name) in checks {
            writeln!(lock, "check\t{file}\t{job_path}\t{check_name}")?;
        }
    }
    Ok(lock)
}

/// Append `(job id path, check name)` for each job of `workflow`, prefixed by
/// the calling job when this workflow was reached through a call.
fn collect_checks(
    workflows: &BTreeMap<&str, Value>,
    file: &str,
    workflow: &Value,
    id_prefix: &str,
    name_prefix: &str,
    checks: &mut Vec<(String, String)>,
) -> Result<()> {
    let Some(jobs) = workflow.get("jobs").and_then(Value::as_mapping) else {
        bail!("{file} has no jobs");
    };

    for (id, job) in jobs {
        let id = id
            .as_str()
            .with_context(|| format!("{file} has a non-string job id"))?;
        let name = job.get("name").and_then(Value::as_str).unwrap_or(id);
        let job_path = format!("{id_prefix}{id}");
        let check_name = format!("{name_prefix}{name}");

        let called = job
            .get("uses")
            .and_then(Value::as_str)
            .and_then(|uses| uses.strip_prefix("./.github/workflows/"));
        match called {
            Some(called_file) => {
                let callee = workflows.get(called_file).with_context(|| {
                    format!("{file} job `{id}` calls {called_file}, which is not generated")
                })?;
                collect_checks(
                    workflows,
                    called_file,
                    callee,
                    &format!("{job_path}/"),
                    &format!("{check_name} / "),
                    checks,
                )?;
            }
            None => checks.push((job_path, check_name)),
        }
    }
    Ok(())
}

