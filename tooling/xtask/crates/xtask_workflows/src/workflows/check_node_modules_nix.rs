//! `check node_modules nix` — verifies the fixed-output Bun `node_modules`
//! derivation still matches the committed lockfile/package manifests. Generated
//! into `check_node_modules_nix.yml`.
//!
//! The Darwin check runs on a macOS runner, billed at ten times a Linux one,
//! and most of its runs repeat a check already passed: every push to a PR that
//! touches a manifest runs it, whatever the push changed. So a Linux job first
//! evaluates the Darwin derivation and looks it up in Namespace's remote cache,
//! where a passed check leaves a marker named after the derivation and kept
//! per version of this workflow, so a changed check starts afresh. The
//! derivation path covers every input of the build (the lockfile, manifests,
//! patches, Bun, and the expected hash), so a marker for it is the answer the
//! macOS build would give again.

use gh_workflow::{Event, Expression, Job, Level, Permissions, Step, Workflow, WorkflowCall};
use xtask_paths::RepoGlob;

use crate::workflows::{runners, steps, vars};

#[cfg(test)]
mod test;

/// Files whose change makes `PR CI` call this workflow.
pub const PATHS: &[RepoGlob<'static>] = &[
    xtask_paths::repo_glob!("bun.lock"),
    xtask_paths::repo_glob!("package.json"),
    xtask_paths::repo_glob!("apps/**/package.json"),
    xtask_paths::repo_glob!("packages/**/package.json"),
    xtask_paths::repo_glob!("services/**/package.json"),
    xtask_paths::repo_glob!("apps/web/patches/**"),
    xtask_paths::repo_glob!("nix-support/node_modules.nix"),
    xtask_paths::repo_glob!("nix-support/node_modules-hashes.json"),
    xtask_paths::repo_glob!("nix/tauri-desktop.nix"),
    xtask_paths::repo_glob!("tooling/scripts/update-node-modules-hash.sh"),
    xtask_paths::repo_glob!("flake.nix"),
    xtask_paths::repo_glob!("flake.lock"),
    xtask_paths::repo_glob!(".github/workflows/check_node_modules_nix.yml"),
];

const LOOKUP_JOB: &str = "find-darwin-node-modules-nix";
const DARWIN_JOB: &str = "check-darwin-node-modules-nix";
const RECORD_JOB: &str = "record-darwin-node-modules-nix";
const MARKER_SCRIPT: &str = include_str!("scripts/node_modules_check_marker.ts");

/// Build the workflow.
pub fn check_node_modules_nix() -> Workflow {
    Workflow::new("check node_modules nix")
        .permissions(Permissions {
            contents: Some(Level::Read),
            ..Default::default()
        })
        .on(Event::default().workflow_call(WorkflowCall::default()))
        .add_job(
            "check-linux-node-modules-nix",
            check_linux_node_modules_nix(),
        )
        .add_job(LOOKUP_JOB, find_darwin_node_modules_nix())
        .add_job(DARWIN_JOB, check_darwin_node_modules_nix())
        .add_job(RECORD_JOB, record_darwin_node_modules_nix())
}

fn check_linux_node_modules_nix() -> Job {
    Job::default()
        .timeout_minutes(15u32)
        .name("check Linux node_modules nix")
        .runs_on(runners::Runner::Small.to_string())
        .add_step(steps::checkout(false, false))
        .add_step(steps::mount_nix_cache_volume())
        .add_step(steps::setup_nix())
        .add_step(verify_node_modules_nix())
        .add_step(steps::teardown_nix())
}

/// The workflow the check runs in: markers are kept per version of it.
const WORKFLOW_FILE: &str = ".github/workflows/check_node_modules_nix.yml";

fn find_darwin_node_modules_nix() -> Job {
    Job::default()
        .timeout_minutes(10u32)
        .name("find a passed Darwin node_modules check")
        .runs_on(runners::Runner::Small.to_string())
        .add_output("passed", "${{ steps.lookup.outputs.passed }}")
        .add_output("drv", "${{ steps.eval.outputs.drv }}")
        .add_output("version", "${{ steps.eval.outputs.version }}")
        .add_step(steps::checkout(false, false))
        .add_step(steps::mount_nix_cache_volume())
        .add_step(steps::setup_nix())
        // A failed evaluation or lookup leaves `passed` empty, so the Darwin
        // check runs instead of the workflow failing here.
        .add_step(
            Step::new("Evaluate the Darwin node_modules derivation")
                .run(indoc::indoc! {r#"
                    set -euo pipefail
                    echo "version=$CHECK_VERSION" >> "$GITHUB_OUTPUT"
                    drv=$(nix eval --raw .#packages.aarch64-darwin.js-node-modules.drvPath)
                    echo "drv=$(basename "$drv")" >> "$GITHUB_OUTPUT"
                    echo "Darwin node_modules derivation: $drv"
                "#})
                .shell("bash")
                .id("eval")
                .continue_on_error(true)
                .add_env((
                    "CHECK_VERSION",
                    format!("${{{{ hashFiles('{WORKFLOW_FILE}') }}}}"),
                )),
        )
        // Forks have no remote cache credentials, so their check always runs.
        .add_step(
            Step::new("Look up a passed check")
                .run(steps::node_script(MARKER_SCRIPT))
                .shell("bash")
                .id("lookup")
                .continue_on_error(true)
                .if_condition(Expression::new(steps::TRUSTED_NAMESPACE_SCCACHE_CONTEXT))
                .add_env(("MARKER_MODE", "lookup"))
                .add_env(("CACHE_NAME", vars::CI_SCCACHE_NAME))
                .add_env(("CHECK_VERSION", "${{ steps.eval.outputs.version }}"))
                .add_env(("DRV", "${{ steps.eval.outputs.drv }}")),
        )
        .add_step(steps::teardown_nix())
}

fn check_darwin_node_modules_nix() -> Job {
    Job::default()
        // The runner keeps no Nix store, so each run downloads nixpkgs and the
        // toolchain first: 12 of a run's 14 minutes on a slow night. A run that
        // times out wastes every minute it ran, so leave room.
        .timeout_minutes(25u32)
        .name("check Darwin node_modules nix")
        .runs_on(runners::Runner::MacOsArm.to_string())
        .needs(vec![LOOKUP_JOB.to_string()])
        // Status-aware, so a lookup job that failed outright (checkout, Nix
        // setup) runs the check instead of skipping it.
        .cond(Expression::new(format!(
            "${{{{ !cancelled() && needs.{LOOKUP_JOB}.outputs.passed != 'true' }}}}"
        )))
        .add_output("drv", "${{ steps.drv.outputs.drv }}")
        .add_step(steps::checkout(false, false))
        .add_step(assert_arm64())
        .add_step(install_nix_macos())
        .add_step(verify_node_modules_nix())
        // The marker names the derivation macOS built, so a Linux evaluation
        // that ever differed would miss the marker rather than skip a check.
        .add_step(
            Step::new("Name the checked derivation")
                .run(indoc::indoc! {r#"
                    set -euo pipefail
                    echo "drv=$(basename "$(nix eval --raw .#js-node-modules.drvPath)")" >> "$GITHUB_OUTPUT"
                "#})
                .shell("bash")
                .id("drv"),
        )
}

/// Leave the marker from Linux, where `nsc` issues the cache credentials.
fn record_darwin_node_modules_nix() -> Job {
    Job::default()
        .timeout_minutes(5u32)
        .name("record the passed Darwin node_modules check")
        .runs_on(runners::Runner::TinyNoCache.to_string())
        .needs(vec![LOOKUP_JOB.to_string(), DARWIN_JOB.to_string()])
        .cond(Expression::new(format!(
            "${{{{ needs.{DARWIN_JOB}.result == 'success' && ({}) }}}}",
            steps::TRUSTED_NAMESPACE_SCCACHE_CONTEXT
        )))
        .add_step(
            Step::new("Record the passed check")
                .run(steps::node_script(MARKER_SCRIPT))
                .shell("bash")
                .add_env(("MARKER_MODE", "record"))
                .add_env((
                    "CHECK_VERSION",
                    format!("${{{{ needs.{LOOKUP_JOB}.outputs.version }}}}"),
                ))
                .add_env(("CACHE_NAME", vars::CI_SCCACHE_NAME))
                .add_env(("DRV", format!("${{{{ needs.{DARWIN_JOB}.outputs.drv }}}}")))
                .add_env((
                    "LINUX_DRV",
                    format!("${{{{ needs.{LOOKUP_JOB}.outputs.drv }}}}"),
                ))
                .add_env((
                    "RUN_URL",
                    "${{ github.server_url }}/${{ github.repository }}/actions/runs/${{ github.run_id }}",
                )),
        )
}

fn assert_arm64() -> Step<gh_workflow::Run> {
    Step::new("Assert arm64 runner")
        .run(indoc::indoc! {r#"
            set -euo pipefail
            if [ "$(uname -m)" != "arm64" ]; then
              echo "macOS node_modules checks must run on an arm64/aarch64 runner, got $(uname -m)" >&2
              exit 1
            fi
        "#})
        .shell("bash")
}

fn install_nix_macos() -> Step<gh_workflow::Run> {
    Step::new("Install Nix")
        .run(include_str!("scripts/install_nix_macos.sh"))
        .shell("bash")
}

fn verify_node_modules_nix() -> Step<gh_workflow::Run> {
    Step::new("verify js node_modules derivation is up to date").run(indoc::indoc! {r#"
        # A fixed-output derivation already in the store is accepted without
        # running it, whatever bun.lock now says, so only then does the check
        # need a rebuild. On a store without it, the first build is the check.
        out=$(nix eval --raw .#js-node-modules.outPath)
        if nix-store --check-validity "$out" 2>/dev/null; then
          nix build .#js-node-modules --no-link --rebuild
        else
          nix build .#js-node-modules --no-link
        fi
    "#})
}
