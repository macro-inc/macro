//! `check node_modules nix` — verifies the fixed-output Bun `node_modules`
//! derivation still matches the committed lockfile/package manifests. Generated
//! into `check_node_modules_nix.yml`.

use gh_workflow::{Event, Job, Level, Permissions, Step, Workflow, WorkflowCall};
use xtask_paths::RepoGlob;

use crate::workflows::{runners, steps};

/// Files whose change makes `PR CI` call this workflow.
pub const PATHS: &[RepoGlob<'static>] = &[
    xtask_paths::repo_glob!("bun.lock"),
    xtask_paths::repo_glob!("package.json"),
    xtask_paths::repo_glob!("apps/**/package.json"),
    xtask_paths::repo_glob!("packages/**/package.json"),
    xtask_paths::repo_glob!("services/**/package.json"),
    xtask_paths::repo_glob!("apps/web/patches/**"),
    xtask_paths::repo_glob!("nix-support/node_modules.nix"),
    xtask_paths::repo_glob!("nix-support/node_modules-hashes.json"),
    xtask_paths::repo_glob!("nix/tauri-desktop.nix"),
    xtask_paths::repo_glob!("tooling/scripts/update-node-modules-hash.sh"),
    xtask_paths::repo_glob!("flake.nix"),
    xtask_paths::repo_glob!("flake.lock"),
    xtask_paths::repo_glob!(".github/workflows/check_node_modules_nix.yml"),
];

/// Build the workflow.
pub fn check_node_modules_nix() -> Workflow {
    Workflow::new("check node_modules nix")
        .permissions(Permissions {
            contents: Some(Level::Read),
            ..Default::default()
        })
        .on(Event::default().workflow_call(WorkflowCall::default()))
        .add_job(
            "check-linux-node-modules-nix",
            check_linux_node_modules_nix(),
        )
        .add_job(
            "check-darwin-node-modules-nix",
            check_darwin_node_modules_nix(),
        )
}

fn check_linux_node_modules_nix() -> Job {
    Job::default()
        .timeout_minutes(15u32)
        .name("check Linux node_modules nix")
        .runs_on(runners::Runner::Small.to_string())
        .add_step(steps::checkout(false, false))
        .add_step(steps::mount_nix_cache_volume())
        .add_step(steps::setup_nix())
        .add_step(verify_node_modules_nix())
        .add_step(steps::teardown_nix())
}

fn check_darwin_node_modules_nix() -> Job {
    Job::default()
        .timeout_minutes(15u32)
        .name("check Darwin node_modules nix")
        .runs_on(runners::Runner::MacOsArm.to_string())
        .add_step(steps::checkout(false, false))
        .add_step(assert_arm64())
        .add_step(install_nix_macos())
        .add_step(verify_node_modules_nix())
}

fn assert_arm64() -> Step<gh_workflow::Run> {
    Step::new("Assert arm64 runner")
        .run(indoc::indoc! {r#"
            set -euo pipefail
            if [ "$(uname -m)" != "arm64" ]; then
              echo "macOS node_modules checks must run on an arm64/aarch64 runner, got $(uname -m)" >&2
              exit 1
            fi
        "#})
        .shell("bash")
}

fn install_nix_macos() -> Step<gh_workflow::Run> {
    Step::new("Install Nix")
        .run(include_str!("scripts/install_nix_macos.sh"))
        .shell("bash")
}

fn verify_node_modules_nix() -> Step<gh_workflow::Run> {
    Step::new("verify js node_modules derivation is up to date").run(indoc::indoc! {r#"
        # A fixed-output derivation already in the store is accepted without
        # running it, whatever bun.lock now says, so only then does the check
        # need a rebuild. On a store without it, the first build is the check.
        out=$(nix eval --raw .#js-node-modules.outPath)
        if nix-store --check-validity "$out" 2>/dev/null; then
          nix build .#js-node-modules --no-link --rebuild
        else
          nix build .#js-node-modules --no-link
        fi
    "#})
}
