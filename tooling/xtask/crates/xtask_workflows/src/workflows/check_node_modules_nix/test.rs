use super::*;

fn rendered() -> serde_yaml::Value {
    serde_yaml::from_str(&check_node_modules_nix().to_string().unwrap()).unwrap()
}

#[test]
fn darwin_check_runs_only_without_a_passed_marker() {
    let workflow = rendered();
    let darwin = &workflow["jobs"][DARWIN_JOB];
    assert_eq!(darwin["needs"][0], LOOKUP_JOB);
    assert_eq!(
        darwin["if"],
        format!("${{{{ !cancelled() && needs.{LOOKUP_JOB}.outputs.passed != 'true' }}}}")
    );
    let lookup = &workflow["jobs"][LOOKUP_JOB];
    assert!(
        lookup["runs-on"]
            .as_str()
            .unwrap()
            .starts_with("namespace-profile-linux")
    );
    let lookup_step = lookup["steps"]
        .as_sequence()
        .unwrap()
        .iter()
        .find(|step| step["id"] == "lookup")
        .unwrap();
    // Forks never get the cache token.
    assert_eq!(lookup_step["if"], steps::TRUSTED_NAMESPACE_SCCACHE_CONTEXT);
    // A failed evaluation or lookup falls back to running the check.
    for step in lookup["steps"].as_sequence().unwrap() {
        if step["id"] == "eval" || step["id"] == "lookup" {
            assert_eq!(step["continue-on-error"], true, "{step:?}");
        }
    }
    // Markers are kept per version of the workflow that runs the check.
    assert!(
        serde_yaml::to_string(&lookup["steps"])
            .unwrap()
            .contains(&format!("hashFiles('{WORKFLOW_FILE}')"))
    );
}

#[test]
fn only_a_passed_darwin_check_is_recorded() {
    let workflow = rendered();
    let record = &workflow["jobs"][RECORD_JOB];
    let condition = record["if"].as_str().unwrap();
    assert!(condition.contains(&format!("needs.{DARWIN_JOB}.result == 'success'")));
    assert!(condition.contains(steps::TRUSTED_NAMESPACE_SCCACHE_CONTEXT));
    let env = &record["steps"][0]["env"];
    assert_eq!(env["MARKER_MODE"], "record");
    assert_eq!(
        env["DRV"],
        format!("${{{{ needs.{DARWIN_JOB}.outputs.drv }}}}")
    );
}

#[test]
fn marker_script_scenarios() {
    let output = std::process::Command::new("node")
        .args(["--test", "node_modules_check_marker.test.ts"])
        .current_dir(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/src/workflows/scripts"
        ))
        .output()
        .expect("run the marker scenarios with Node");
    assert!(
        output.status.success(),
        "{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}
