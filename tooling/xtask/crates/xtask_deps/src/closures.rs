//! Generates .github/workspace-dep-closures.json: for every workspace
//! member, the directories (relative to the workspace root) of the member
//! plus every workspace crate in its transitive dependency closure.
//!
//! flake.nix uses the map to give each deploy artifact a pruned source tree,
//! so a leaf derivation's hash only moves when a crate it actually depends on
//! changes. Closures follow normal and build edges but not dev-only edges:
//! deploy artifacts are built with `cargo build --bin`, which never compiles
//! dev-deps, and including them would only widen closures. A superset closure
//! is sound (at worst a spurious rebuild); a missing crate fails the build
//! loudly inside the nix sandbox.
//!
//! The file also holds `wasm_closures` for the crates apps/web builds for the
//! browser ([`WASM_PACKAGES`]): only the workspace crates a wasm32 build of the
//! package can compile. `apps/web/scripts/wasm-cache-key.ts` hashes them to
//! decide whether a wasm package must be rebuilt. The plain closure also
//! follows links that are off on wasm32 or behind features that build never
//! enables, so about a third of main's commits changed the cache WASM's key
//! without changing anything it compiles.

use std::collections::{BTreeMap, BTreeSet};
use std::sync::Arc;

use anyhow::{Context, Result};
use guppy::graph::cargo::{CargoOptions, CargoResolverVersion, CargoSet};
use guppy::graph::feature::StandardFeatures;
use guppy::graph::{DependencyDirection, PackageGraph, PackageMetadata};
use guppy::platform::{Platform, PlatformSpec, TargetFeatures};

#[cfg(test)]
mod test;

const OUTPUT_REL: &str = ".github/workspace-dep-closures.json";

/// The packages `apps/web/justfile` passes to `scripts/cached-wasm-build.sh`,
/// whose key script refuses a package missing here.
pub(crate) const WASM_PACKAGES: &[&str] = &[
    "agent_fold",
    "ai_engine",
    "cache-wasm",
    "database_sql",
    "docx_engine",
    "fig_engine",
    "natural_time",
    "password_import_wasm",
    "pptx_engine",
    "psd_engine",
];

const WASM_TARGET: &str = "wasm32-unknown-unknown";

/// Regenerates (or, in check mode, diffs) the closure map.
pub fn run(graph: &PackageGraph, check: bool, drift: &mut Vec<String>) -> Result<()> {
    let workspace = graph.workspace();
    let ws_root = workspace.root();
    let repo_root = ws_root;
    let output_path = repo_root.join(OUTPUT_REL);

    let mut closures: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for member in workspace.iter() {
        closures.insert(member.name().to_owned(), closure(graph, member)?);
    }

    let wasm_closures = WASM_PACKAGES
        .iter()
        .map(|name| Ok(((*name).to_owned(), wasm_closure(graph, name)?)))
        .collect::<Result<BTreeMap<_, _>>>()?;

    let doc = serde_json::json!({
        "//": "Generated by `cargo run -p xtask -- deps` (see tooling/xtask); do not edit by hand. Maps every Rust workspace crate to the directories of its transitive workspace dependency closure (normal + build deps, dev-deps excluded). Consumed by flake.nix to build pruned per-artifact deploy sources. `wasm_closures` narrows the browser wasm packages to what a wasm32 build with every feature on can compile; apps/web/scripts/wasm-cache-key.ts hashes them.",
        "closures": closures,
        "wasm_closures": wasm_closures,
    });
    let new_contents =
        serde_json::to_string_pretty(&doc).context("serializing closure map")? + "\n";

    let current = std::fs::read_to_string(&output_path).unwrap_or_default();
    if current != new_contents {
        if check {
            drift.push(OUTPUT_REL.to_owned());
        } else {
            std::fs::write(&output_path, &new_contents)
                .with_context(|| format!("writing {output_path}"))?;
            println!("updated {OUTPUT_REL} ({} members)", closures.len());
        }
    }
    Ok(())
}

/// The directories of `member` and every workspace crate it reaches over
/// normal and build edges, on any platform and with any features.
pub(crate) fn closure(
    graph: &PackageGraph,
    member: PackageMetadata<'_>,
) -> Result<BTreeSet<String>> {
    // Follow only links that stay inside the workspace (registry deps cannot
    // depend back into it) and are not dev-only.
    let set = graph
        .query_forward([member.id()])
        .context("querying workspace member")?
        .resolve_with_fn(|_, link| link.to().in_workspace() && !link.dev_only());
    workspace_dirs(graph, set.packages(DependencyDirection::Forward))
}

/// The workspace crates a `wasm32-unknown-unknown` build of `name` compiles,
/// with every feature of `name` on, as cargo's v2 resolver picks them: target
/// dependencies for wasm32, plus build scripts and proc macros (and what they
/// use) for any host. Enabling every feature makes it a superset of each
/// feature choice a build command makes, such as `--no-default-features`.
pub(crate) fn wasm_closure(graph: &PackageGraph, name: &str) -> Result<BTreeSet<String>> {
    let package = graph
        .workspace()
        .member_by_name(name)
        .with_context(|| format!("no workspace member {name}"))?;
    let wasm32 = Platform::new(WASM_TARGET, TargetFeatures::Unknown)
        .with_context(|| format!("parsing {WASM_TARGET}"))?;
    let mut options = CargoOptions::new();
    options
        .set_resolver(CargoResolverVersion::V2)
        .set_include_dev(false)
        .set_target_platform(PlatformSpec::Platform(Arc::new(wasm32)))
        .set_host_platform(PlatformSpec::Any);
    let initials = graph
        .resolve_ids([package.id()])
        .context("resolving the wasm package")?
        .to_feature_set(StandardFeatures::All);
    let features_only = graph.resolve_none().to_feature_set(StandardFeatures::All);
    let build = CargoSet::new(initials, features_only, &options)
        .with_context(|| format!("resolving the wasm32 build of {name}"))?;
    let compiled = build
        .target_features()
        .to_package_set()
        .union(&build.host_features().to_package_set());
    workspace_dirs(graph, compiled.packages(DependencyDirection::Forward))
}

/// The directories, relative to the workspace root, of the workspace crates
/// among `packages`.
fn workspace_dirs<'g>(
    graph: &'g PackageGraph,
    packages: impl Iterator<Item = PackageMetadata<'g>>,
) -> Result<BTreeSet<String>> {
    let ws_root = graph.workspace().root();
    packages
        .filter(|p| p.in_workspace())
        .map(|p| {
            let dir = p
                .manifest_path()
                .parent()
                .with_context(|| format!("manifest {} has no parent", p.manifest_path()))?;
            Ok(dir
                .strip_prefix(ws_root)
                .with_context(|| format!("{dir} is outside the workspace root"))?
                .as_str()
                .to_owned())
        })
        .collect()
}
