import { execFileSync } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "../..");
const TOOLING_DIRECTORY = "tooling/icons";
const WEB_DIRECTORY = "apps/web";
const GENERATOR_PATH = `${TOOLING_DIRECTORY}/generate-entity-icons.ts`;
const CATALOG_DIRECTORY = "packages/entity-icons";
const ICON_DIRECTORY = `${CATALOG_DIRECTORY}/svg`;
const ICON_NAMES_PATH = `${CATALOG_DIRECTORY}/names.json`;
const ICON_ALIASES_PATH = `${CATALOG_DIRECTORY}/aliases.json`;
const ICON_SECTIONS_PATH = `${CATALOG_DIRECTORY}/sections.json`;
const CATALOG_PATH = `${CATALOG_DIRECTORY}/catalog.generated.ts`;
const HISTORICAL_NAMES_PATHS = [
	`${TOOLING_DIRECTORY}/entity-icon-names.json`,
	ICON_NAMES_PATH,
];
const RUST_CATALOG_PATH =
	"crates/model-entity/src/appearance_icons.generated.rs";
const WEB_LABELS_PATH = `${WEB_DIRECTORY}/src/lib/i18n/locales/en/entity-icons.ts`;
const GENERATED = `// Generated by ${GENERATOR_PATH}. Do not edit.\n`;

type IconSection = {
	id: string;
	label: string;
	icons: { name: string; label: string }[];
};

/** Validate the permanent storage vocabulary separately from picker curation. */
export function validateCatalog(
	icons: ReadonlyMap<string, string>,
	permanentNames: readonly string[],
	aliases: Readonly<Record<string, string>>,
	sections: readonly IconSection[],
) {
	const geometryNames = new Map<string, string>();
	for (const [name, svg] of icons) {
		const geometry = svg
			.replace(
				/\s+(?:data-[\w:-]+|aria-[\w:-]+|xmlns(?::[\w-]+)?|role|focusable)\s*=\s*(['"])[\s\S]*?\1/g,
				"",
			)
			.replace(/\s+/g, " ")
			.replace(/>\s+</g, "><")
			.replace(/\s+\/>/g, "/>")
			.trim();
		const previous = geometryNames.get(geometry);
		if (previous)
			throw new Error(`Identical icon geometry: ${previous}, ${name}`);
		geometryNames.set(geometry, name);
	}
	for (const [name, target] of Object.entries(aliases)) {
		if (icons.has(name)) throw new Error(`Alias shadows an icon: ${name}`);
		if (!icons.has(target))
			throw new Error(`Alias target is not an icon: ${name} -> ${target}`);
	}
	const names = [...icons.keys(), ...Object.keys(aliases)].sort();
	const allowed = new Set(names);
	for (const name of names) {
		if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name))
			throw new Error(`Invalid icon name: ${name}`);
	}
	for (const name of permanentNames) {
		if (!allowed.has(name))
			throw new Error(`Permanent icon removed without an alias: ${name}`);
	}
	const sectionIds = new Set<string>();
	const selected = new Set<string>();
	for (const section of sections) {
		if (!section.label.trim() || sectionIds.has(section.id))
			throw new Error(`Invalid or duplicate section: ${section.id}`);
		sectionIds.add(section.id);
		for (const { name, label } of section.icons) {
			if (!icons.has(name))
				throw new Error(`Unknown picker icon in ${section.id}: ${name}`);
			if (!label.trim()) throw new Error(`Missing icon label: ${name}`);
			if (selected.has(name))
				throw new Error(`Icon belongs to multiple sections: ${name}`);
			selected.add(name);
		}
	}
	return { names, selected };
}

/** Recover the append-only vocabulary even if the working manifest was trimmed. */
export function committedIconNames(root: string): string[] {
	const git = (...args: string[]) =>
		execFileSync("git", args, {
			cwd: root,
			encoding: "utf8",
			stdio: ["ignore", "pipe", "pipe"],
		}).trim();
	if (git("rev-parse", "--is-shallow-repository") === "true") {
		throw new Error(
			"Icon permanence checks need full Git history; run git fetch --unshallow",
		);
	}
	const names = new Set<string>();
	// Read both manifest locations across all merge parents. Skip deletion commits
	// and treat moves as additions/deletions so a rename cannot erase old names.
	for (const path of HISTORICAL_NAMES_PATHS) {
		const revisions = git(
			"log",
			"--full-history",
			"--no-renames",
			"--diff-filter=AM",
			"--format=%H",
			"--",
			path,
		);
		for (const revision of revisions.split("\n").filter(Boolean)) {
			const previous: string[] = JSON.parse(git("show", `${revision}:${path}`));
			for (const name of previous) names.add(name);
		}
	}
	return [...names];
}
async function main() {
	const directory = resolve(ROOT, ICON_DIRECTORY);
	const icons = new Map<string, string>();
	for (const file of (await readdir(directory)).sort()) {
		if (!file.endsWith(".svg")) continue;
		icons.set(
			file.slice(0, -4),
			await readFile(resolve(directory, file), "utf8"),
		);
	}
	const permanentNames: string[] = JSON.parse(
		await readFile(resolve(ROOT, ICON_NAMES_PATH), "utf8"),
	);
	const aliases: Record<string, string> = JSON.parse(
		await readFile(resolve(ROOT, ICON_ALIASES_PATH), "utf8"),
	);
	const sections: IconSection[] = JSON.parse(
		await readFile(resolve(ROOT, ICON_SECTIONS_PATH), "utf8"),
	);
	const { names, selected } = validateCatalog(
		icons,
		[...permanentNames, ...committedIconNames(ROOT)],
		aliases,
		sections,
	);
	const json = (value: unknown) => JSON.stringify(value, null, 2);
	const labels = Object.fromEntries([
		...sections.map(({ id, label }) => [`section_${id}`, label]),
		...sections.flatMap(({ icons }) =>
			icons.map(({ name, label }) => [`icon_${name}`, label]),
		),
	]);
	const outputs = [
		[ICON_NAMES_PATH, `${json(names)}\n`],
		[
			RUST_CATALOG_PATH,
			GENERATED +
				"pub(super) const ICON_NAMES: &[&str] = &[\n" +
				names.map((name) => `    ${JSON.stringify(name)},`).join("\n") +
				"\n];\n",
		],
		[
			CATALOG_PATH,
			GENERATED +
				`export const ENTITY_ICON_NAMES = ${json(names)} as const;\nexport const ENTITY_ICON_ALIASES: Readonly<Partial<Record<string, (typeof ENTITY_ICON_NAMES)[number]>>> = ${json(aliases)};\nexport const ICON_SECTIONS = ${json(sections)} as const;\n`,
		],
		[WEB_LABELS_PATH, GENERATED + `export default ${json(labels)};\n`],
	];
	const check = process.argv.includes("--check");
	for (const [path, raw] of outputs) {
		let content = raw;
		if (path.endsWith(".ts")) {
			const formatted = Bun.spawnSync(
				[
					"bunx",
					"--bun",
					"@biomejs/biome",
					"format",
					`--stdin-file-path=${resolve(ROOT, path)}`,
				],
				{
					cwd: resolve(ROOT, WEB_DIRECTORY),
					stdin: new TextEncoder().encode(raw),
					stdout: "pipe",
					stderr: "pipe",
				},
			);
			if (formatted.exitCode !== 0)
				throw new Error(formatted.stderr.toString());
			content = formatted.stdout.toString();
		}
		const target = resolve(ROOT, path);
		if (check) {
			if ((await readFile(target, "utf8")) !== content)
				throw new Error(
					`Stale icon catalog: ${path}. Run bun ${GENERATOR_PATH}`,
				);
		} else {
			await writeFile(target, content);
		}
	}
	console.log(
		`Validated ${names.length} permanent entity icons and ${selected.size} picker icons.`,
	);
}

if (import.meta.main) await main();
