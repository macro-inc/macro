import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import sections from "./entity-icon-sections.json";

// The same catalog validates stored names and supplies the searchable picker.
const root = resolve(import.meta.dirname, "../..");
const directory = resolve(root, "apps/web/src/components/icon/system/regular");
const seen = new Set<string>();
const names: string[] = [];
for (const file of (await readdir(directory)).sort()) {
	if (!file.endsWith(".svg")) continue;
	const name = file.slice(0, -4);
	if (
		/^(caret-|number-|priority-|spinner|check$|checks$|warning|prohibit|github-logo|google-logo)/.test(
			name,
		)
	)
		continue;
	if (/-(slash|off|x|check|active|filled)$/.test(name)) continue;
	const geometry = (await readFile(resolve(directory, file), "utf8")).replace(
		/ data-macro-icon="[^"]*"/g,
		"",
	);
	if (seen.has(geometry)) continue;
	seen.add(geometry);
	names.push(name);
}
const catalog = new Set(names);
const selected = new Set<string>();
for (const section of sections) {
	for (const name of section.names) {
		if (!catalog.has(name))
			throw new Error(`Unknown icon in ${section.id}: ${name}`);
		if (selected.has(name))
			throw new Error(`Icon belongs to multiple sections: ${name}`);
		selected.add(name);
	}
}
const outputs = [
	[
		"crates/model-entity/src/appearance_icons.generated.rs",
		"// Generated by tooling/icons/generate-entity-icons.ts. Do not edit.\n" +
			"pub(super) const ICON_NAMES: &[&str] = &[\n" +
			names.map((name) => `    ${JSON.stringify(name)},`).join("\n") +
			"\n];\n",
	],
	[
		"apps/web/src/features/entity-appearance/core/catalog.generated.ts",
		"// Generated by tooling/icons/generate-entity-icons.ts. Do not edit.\n" +
			"export const ENTITY_ICON_NAMES = " +
			JSON.stringify(names, null, 2) +
			" as const;\n" +
			"export const ICON_SECTIONS = " +
			JSON.stringify(sections, null, 2) +
			" as const;\n",
	],
] as const;
for (const [path, content] of outputs) {
	await writeFile(resolve(root, path), content);
}
console.log(
	`Validated ${names.length} distinct entity icons and ${selected.size} picker icons.`,
);
