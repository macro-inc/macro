import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// The same catalog validates stored names and supplies the searchable picker.
const root = resolve(import.meta.dirname, '../..');
const directory = resolve(root, 'apps/web/src/components/icon/system/regular');
const seen = new Set<string>();
const names: string[] = [];
for (const file of (await readdir(directory)).sort()) {
  if (!file.endsWith('.svg')) continue;
  const name = file.slice(0, -4);
  if (/^(caret-|number-|priority-|spinner|check$|checks$|warning|prohibit|github-logo|google-logo)/.test(name)) continue;
  if (/-(slash|off|x|check|active|filled)$/.test(name)) continue;
  const geometry = (await readFile(resolve(directory, file), 'utf8')).replace(/ data-macro-icon="[^"]*"/g, '');
  if (seen.has(geometry)) continue;
  seen.add(geometry);
  names.push(name);
}
await writeFile(resolve(root, 'crates/model-entity/src/appearance-icons.txt'), names.join('\n') + '\n');
await writeFile(resolve(root, 'apps/web/src/features/entity-appearance/core/catalog.generated.ts'),
  '// Generated by tooling/icons/generate-entity-icons.ts. Do not edit.\n' +
  'export const ENTITY_ICON_NAMES = ' + JSON.stringify(names, null, 2) + ' as const;\n');
console.log(`Generated ${names.length} distinct entity icons.`);
