/// The character of glyph `gid` in the standard Macintosh glyph order.
pub(super) fn mac_glyph_char(gid: u16) -> Option<char> {
    let code = *MAC_GLYPHS.get(usize::from(gid))?;
    if code == 0 {
        None
    } else {
        char::from_u32(u32::from(code))
    }
}
