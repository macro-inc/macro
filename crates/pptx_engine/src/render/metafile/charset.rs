fn cp1252(b: u8) -> u32 {
    match b {
        0x80..=0x9F => u32::from(CP1252_HIGH[usize::from(b - 0x80)]),
        _ => u32::from(b),
    }
}

/// Decodes one byte in the code page of `charset`.
fn decode_byte(b: u8, charset: u8) -> u32 {
    if b < 0x80 {
        return u32::from(b);
    }
    let i = usize::from(b - 0x80);
    match charset {
        238 => u32::from(CP1250[i]),
        204 => match b {
            0xC0..=0xFF => 0x0410 + u32::from(b - 0xC0),
            _ => u32::from(CP1251_LOW[i]),
        },
        161 => match b {
            0xD2 | 0xFF => 0,
            0xC0..=0xFE => 0x0390 + u32::from(b - 0xC0),
            _ => u32::from(CP1253_LOW[i]),
        },
        162 => match b {
            0xD0 => 0x011E,
            0xDD => 0x0130,
            0xDE => 0x015E,
            0xF0 => 0x011F,
            0xFD => 0x0131,
            0xFE => 0x015F,
            0x8E | 0x9E => 0,
            _ => cp1252(b),
        },
        _ => cp1252(b),
    }
}

/// Decodes ANSI text. Symbol fonts keep their byte codes (remapped later by face).
pub(super) fn decode_ansi(bytes: &[u8], charset: u8, symbol: bool) -> Vec<char> {
    bytes
        .iter()
        .map(|&b| {
            let code = if symbol || charset == SYMBOL_CHARSET {
                u32::from(b)
            } else {
                decode_byte(b, charset)
            };
            // Undefined codes keep their C1 control value, which has no glyph.
            char::from_u32(if code == 0 { u32::from(b) } else { code }).unwrap_or('\u{FFFD}')
        })
        .collect()
}

