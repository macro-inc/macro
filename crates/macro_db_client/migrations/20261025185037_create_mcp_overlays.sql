-- Pipedream catalog apps that connect through the native MCP stack
-- (mcp_servers, our own OAuth client via dynamic or metadata-document
-- registration) instead of Pipedream. The app keeps its place in the catalog
-- under its Pipedream slug; connecting it authorizes server_url directly.
-- Pipedream connection reads ignore rows for these slugs, and completing a
-- Pipedream connection for one is refused.
--
-- Reference data with no foreign keys: deleting a row hands the app back to
-- Pipedream. Do not overlay an app whose Pipedream grant backs a non-MCP
-- reader (Linear, Jira and Notion imports, Granola sync) until that reader
-- has a native path.
CREATE TABLE mcp_overlays (
    app_slug TEXT PRIMARY KEY CHECK (app_slug ~ '^[a-z0-9_-]+$'),
    server_url TEXT NOT NULL CHECK (server_url LIKE 'https://%'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

