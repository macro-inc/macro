-- Routine suggestions move onto the generation tables they now share with
-- suggestions: one run of hidden sessions per trigger (onboarding, nightly), each
-- session recorded with what it writes. The routine-only tables are copied,
-- not renamed, so a replica still on the previous release keeps working
-- during the deploy; they are dropped once no deployed release reads them.
--
-- Accepted during the deploy window (minutes, routine suggestions behind
-- their flag): what a replica on the previous release writes to the old
-- tables after this copy is invisible to the new code. A generation it starts
-- isn't seen (that person's onboarding may run again, adding a second set of
-- suggestions); one it finishes stays generating here and reads as failed
-- once stale. After a rollback, the previous release finds no generation for
-- people onboarded on this one and ignores `retired_at`. The migration that
-- drops the old tables copies such late rows first.

-- The ALTERs and the foreign key to "User" lock those tables until commit:
-- take them first, before the copy, and don't queue behind long transactions.
SET LOCAL lock_timeout = '5s';

-- What a code-mode invocation's session may do when narrower than its
-- person's access (`generation`: a suggestion generation session), set
-- where its credential is minted and enforced wherever it is accepted.
ALTER TABLE agent_correlations ADD COLUMN scope text;

-- The trace a generation runs in: its sessions' tool calls reach the API
-- without its trace context and record this id to be joined to it.
ALTER TABLE suggestion_generation ADD COLUMN trace_id text;

-- A routine suggestion a nightly session found no longer fits. Hidden like a
-- dismissed one, but a session may suggest the same routine again.
ALTER TABLE routine_suggestion ADD COLUMN retired_at timestamptz;

-- Who gets a nightly run: paid people who loaded the app with suggestions
-- on recently, with the time zone their browser reported, and when their
-- next run is due, in their night. The scheduler reads only who is due.
CREATE TABLE suggestion_audience (
    user_id text PRIMARY KEY REFERENCES "User"(id) ON DELETE CASCADE,
    timezone text NOT NULL,
    seen_at timestamptz NOT NULL,
    next_run_at timestamptz NOT NULL
);

CREATE INDEX suggestion_audience_due_idx ON suggestion_audience (next_run_at);

-- Migration-local UUIDv7 generation for PostgreSQL 14 (uuidv7() needs PG18).
-- Runtime identities continue to be generated by the application.
CREATE FUNCTION pg_temp.generation_uuid() RETURNS UUID LANGUAGE SQL VOLATILE AS $$
    SELECT encode(set_byte(set_byte(bytes, 6, (get_byte(bytes, 6) & 15) | 112),
        8, (get_byte(bytes, 8) & 63) | 128), 'hex')::uuid
    FROM (SELECT overlay(gen_random_bytes(16) placing
        decode(lpad(to_hex((extract(epoch FROM clock_timestamp()) * 1000)::bigint), 12, '0'), 'hex')
        FROM 1 FOR 6) AS bytes) random;
$$;

-- Each person's one routine suggestion generation was their onboarding run.
CREATE TEMP TABLE copied_generation ON COMMIT DROP AS
SELECT pg_temp.generation_uuid() AS id, g.*
FROM routine_suggestion_generation g;

INSERT INTO suggestion_generation (id, user_id, trigger, status, started_at, finished_at)
SELECT id, user_id, 'onboarding', status, started_at, finished_at
FROM copied_generation
ON CONFLICT DO NOTHING;

INSERT INTO suggestion_generation_session
    (session_id, generation_id, user_id, agent_id, kind, surfaces, opened_at, closed_at)
SELECT s.session_id, g.id, s.user_id, s.agent_id, 'routines', s.surfaces, s.opened_at, s.closed_at
FROM routine_suggestion_session s
JOIN copied_generation g ON g.user_id = s.user_id
ON CONFLICT DO NOTHING;

DROP FUNCTION pg_temp.generation_uuid();
