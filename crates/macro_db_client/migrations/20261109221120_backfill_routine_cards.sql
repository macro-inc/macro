-- Every routine a session drafted ("smart" routine suggestions, `routine`
-- set) is now also one suggestion, kept and closed with it. Give each drafted
-- suggestion still open (neither dismissed, retired nor saved as a routine)
-- its suggestion: the routine's name as the title, the reason as the summary, and
-- the keep estimate as the importance, best first, up to the open suggestions
-- limit of 30 counting the open suggestions the person already has. Catalog picks
-- are never suggestions. A suggestion a replica on the previous release drafts
-- after this runs has no suggestion; every path tolerates that.

-- Migration-local UUIDv7 generation for PostgreSQL 14 (uuidv7() needs PG18).
-- Runtime identities continue to be generated by the application.
CREATE FUNCTION pg_temp.suggestion_uuid() RETURNS UUID LANGUAGE SQL VOLATILE AS $$
    SELECT encode(set_byte(set_byte(bytes, 6, (get_byte(bytes, 6) & 15) | 112),
        8, (get_byte(bytes, 8) & 63) | 128), 'hex')::uuid
    FROM (SELECT overlay(gen_random_bytes(16) placing
        decode(lpad(to_hex((extract(epoch FROM clock_timestamp()) * 1000)::bigint), 12, '0'), 'hex')
        FROM 1 FOR 6) AS bytes) random;
$$;

CREATE TEMP TABLE backfilled_suggestion ON COMMIT DROP AS
SELECT ranked.* FROM (
SELECT pg_temp.suggestion_uuid() AS suggestion_id,
       s.id AS routine_suggestion_id,
       s.user_id,
       left(coalesce(nullif(btrim(s.routine->>'name'), ''), 'Suggested routine'), 80) AS title,
       s.reason,
       least(100, greatest(0, round(s.keep_probability * 100)))::smallint AS importance,
       s.session_id,
       s.created_at,
       row_number() OVER (PARTITION BY s.user_id ORDER BY s.keep_probability DESC, s.created_at DESC) AS rank
FROM routine_suggestion s
WHERE s.routine IS NOT NULL
  AND s.dismissed_at IS NULL
  AND s.retired_at IS NULL
  AND NOT EXISTS (SELECT 1 FROM scheduled_action a WHERE a.suggestion_id = s.id)
  AND NOT EXISTS (SELECT 1 FROM suggestion_routine r WHERE r.routine_suggestion_id = s.id)
) ranked
LEFT JOIN (
    SELECT user_id, count(*) AS open FROM suggestion
    WHERE state IN ('proposed', 'accepted')
    GROUP BY user_id
) existing ON existing.user_id = ranked.user_id
WHERE ranked.rank <= 30 - coalesce(existing.open, 0);

INSERT INTO suggestion
    (id, user_id, kind, dedup_key, title, summary, importance, session_id,
     created_at, updated_at, state_changed_at)
SELECT suggestion_id, user_id, 'routine', 'routine_suggestion:' || routine_suggestion_id::text, title,
       reason, importance, session_id, created_at, created_at, created_at
FROM backfilled_suggestion
ON CONFLICT DO NOTHING;

INSERT INTO suggestion_routine (suggestion_id, routine_suggestion_id)
SELECT b.suggestion_id, b.routine_suggestion_id
FROM backfilled_suggestion b
JOIN suggestion i ON i.id = b.suggestion_id
ON CONFLICT DO NOTHING;

DROP FUNCTION pg_temp.suggestion_uuid();
