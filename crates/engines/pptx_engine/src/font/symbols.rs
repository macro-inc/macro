/// Maps a character drawn in symbol font `font` to its Unicode equivalent.
///
/// Characters may be written either as their low byte (`§`) or in the
/// private-use range `U+F020..U+F0FF`.
pub fn remap_symbol(font: SymbolFont, ch: char) -> char {
    let code = ch as u32;
    let byte = if (0xF020..=0xF0FF).contains(&code) {
        code - 0xF000
    } else if (0x20..=0xFF).contains(&code) {
        code
    } else {
        return ch;
    };
    let mapped = match font {
        SymbolFont::Wingdings => WINGDINGS[(byte - 0x20) as usize],
        SymbolFont::Symbol => SYMBOL[(byte - 0x20) as usize],
        SymbolFont::Wingdings2 => WINGDINGS2
            .iter()
            .find(|(b, _)| u32::from(*b) == byte)
            .map_or(0x25AA, |(_, u)| *u),
        SymbolFont::Wingdings3 => WINGDINGS3
            .iter()
            .find(|(b, _)| u32::from(*b) == byte)
            .map_or(0x25B6, |(_, u)| *u),
        SymbolFont::Webdings => 0x25AA,
    };
    char::from_u32(mapped)
        .filter(|_| mapped != 0)
        .unwrap_or('\u{2022}')
}
