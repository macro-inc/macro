//! Remaps characters of legacy symbol fonts (Wingdings, Symbol) to Unicode.
//!
//! Bullets in older decks are frequently `§` or `Ø` in Wingdings, or `·` in
//! Symbol. Those fonts are not redistributable, so the glyphs are mapped to
//! their Unicode equivalents and drawn with a font that has them.

/// A symbol-encoded font family.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SymbolFont {
    /// Wingdings.
    Wingdings,
    /// Wingdings 2.
    Wingdings2,
    /// Wingdings 3.
    Wingdings3,
    /// Adobe Symbol.
    Symbol,
    /// Webdings.
    Webdings,
}

impl SymbolFont {
    /// Detects a symbol font from a (lower-cased) family name.
    pub fn from_family(lower: &str) -> Option<Self> {
        match lower.trim() {
            "wingdings" => Some(Self::Wingdings),
            "wingdings 2" => Some(Self::Wingdings2),
            "wingdings 3" => Some(Self::Wingdings3),
            "symbol" => Some(Self::Symbol),
            "webdings" => Some(Self::Webdings),
            _ => None,
        }
    }
}

