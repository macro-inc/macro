//! `docx_corpus fontconfig`: a fontconfig file that makes LibreOffice use
//! the engine's font files and substitutions for reference renders.

use pptx_engine::font::{MONO_FALLBACK, SANS_FALLBACK, SERIF_FALLBACK, SUBSTITUTES};
use std::path::{Path, PathBuf};

/// Options of `docx_corpus fontconfig`.
#[derive(clap::Args)]
pub struct Args {
    /// Where to write the file (`FONTCONFIG_FILE` for LibreOffice).
    #[arg(long)]
    out: PathBuf,
}

fn escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn document(font_dir: &Path) -> String {
    let mut xml = String::from(
        "<?xml version=\"1.0\"?>\n<!DOCTYPE fontconfig SYSTEM \"fonts.dtd\">\n<!-- Generated by `docx_corpus fontconfig`. -->\n<fontconfig>\n",
    );
    xml.push_str(&format!(
        "  <dir>{}</dir>\n",
        escape(&font_dir.display().to_string())
    ));
    for (family, substitutes) in SUBSTITUTES {
        let Some(first) = substitutes.first() else {
            continue;
        };
        if family.eq_ignore_ascii_case(first) {
            continue;
        }
        xml.push_str(&format!(
            "  <match target=\"pattern\"><test name=\"family\" ignore-blanks=\"true\"><string>{}</string></test><edit name=\"family\" mode=\"assign\" binding=\"strong\"><string>{}</string></edit></match>\n",
            escape(family),
            escape(first)
        ));
    }
    xml.push_str("  <match target=\"pattern\"><test qual=\"all\" name=\"family\" compare=\"not_eq\"><string>sans-serif</string></test><test qual=\"all\" name=\"family\" compare=\"not_eq\"><string>serif</string></test><test qual=\"all\" name=\"family\" compare=\"not_eq\"><string>monospace</string></test><edit name=\"family\" mode=\"append_last\"><string>sans-serif</string></edit></match>\n");
    for (generic, family) in [
        ("sans-serif", SANS_FALLBACK),
        ("serif", SERIF_FALLBACK),
        ("monospace", MONO_FALLBACK),
    ] {
        xml.push_str(&format!(
            "  <alias binding=\"strong\"><family>{generic}</family><prefer><family>{}</family></prefer></alias>\n",
            escape(family)
        ));
    }
    xml.push_str(
        "  <include ignore_missing=\"yes\">/etc/fonts/fonts.conf</include>\n</fontconfig>\n",
    );
    xml
}

/// Runs the command.
pub fn run(args: &Args) -> Result<bool, Box<dyn std::error::Error>> {
    let fonts = Path::new(env!("CARGO_MANIFEST_DIR")).join("../pptx_engine/fonts");
    let fonts = std::fs::canonicalize(&fonts).unwrap_or(fonts);
    std::fs::write(&args.out, document(&fonts))?;
    println!("{}", args.out.display());
    Ok(true)
}
