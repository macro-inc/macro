//! Credential-free audit records written by the transaction that commits an action.

use macro_user_id::user_id::MacroUserIdStr;
use macro_uuid::Uuid;

/// Actions required in the enterprise audit trail.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize, strum::AsRefStr,
)]
#[serde(rename_all = "snake_case")]
#[strum(serialize_all = "snake_case")]
pub enum AuditAction {
    /// A completed sign-in.
    Login,
    /// A newly created team invitation, not a resend.
    Invite,
    /// A share link enabled for an existing resource.
    ShareLinkCreate,
    /// A mailbox provision committed by its owning task.
    MailboxProvision,
    /// A newly persisted agent session.
    AgentSessionStart,
    /// A committed member disable.
    MemberDisable,
    /// A committed member enable.
    MemberEnable,
}

/// Outcome recorded without message contents or credentials.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize, strum::AsRefStr,
)]
#[serde(rename_all = "snake_case")]
#[strum(serialize_all = "snake_case")]
pub enum AuditResult {
    /// The action completed without a declared capability gap.
    Success,
    /// FusionAuth was deactivated; the external mailbox has no suspend route.
    MailSuspendGap,
}

/// One append-only audit row. This type deliberately has no payload or secret fields.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AuditRecord {
    /// UUIDv7 row identity generated by the caller.
    pub id: Uuid,
    /// Person or internal principal that performed the action.
    pub actor_id: String,
    /// Committed action.
    pub action: AuditAction,
    /// Opaque id of the affected resource.
    pub resource_id: String,
    /// Committed result or typed capability gap.
    pub result: AuditResult,
}

impl AuditRecord {
    /// Construct an audit row for a known actor and resource.
    #[must_use]
    pub fn new(
        actor: &MacroUserIdStr<'_>,
        action: AuditAction,
        resource_id: impl Into<String>,
        result: AuditResult,
    ) -> Self {
        Self {
            id: macro_uuid::generate_uuid_v7(),
            actor_id: actor.as_ref().to_owned(),
            action,
            resource_id: resource_id.into(),
            result,
        }
    }
}

/// Insert an audit row inside the committing transaction.
#[cfg(feature = "outbound")]
pub async fn append(
    transaction: &mut sqlx::Transaction<'_, sqlx::Postgres>,
    record: &AuditRecord,
) -> Result<(), sqlx::Error> {
    sqlx::query!(
        r#"
        INSERT INTO enterprise_audit (id, actor_id, action, resource_id, result)
        VALUES ($1, $2, $3, $4, $5)
        "#,
        record.id,
        record.actor_id.as_str(),
        record.action.as_ref(),
        record.resource_id.as_str(),
        record.result.as_ref(),
    )
    .execute(transaction.as_mut())
    .await?;
    Ok(())
}
