//! Generate the TypeScript declaration consumed by the development postcard decoder.
use clap::Parser;
use lexical_conformance_wasm::host_packet::HostCommitPacket;
use specta::Types;
use specta_typescript::Typescript;
use std::{
    io::Write,
    path::Path,
    process::{Command, Stdio},
};

#[derive(Parser)]
struct Args {
    #[arg(long)]
    check: bool,
}

fn main() -> Result<(), rootcause::Report> {
    let args = Args::parse();
    let types = Types::default().register::<HostCommitPacket>();
    let generated = Typescript::default()
        .export(&types, specta_serde::PhasesFormat)
        .map_err(rootcause::Report::new)?;
    let generated = format!(
        "// Generated by lexical_conformance_wasm --example export_host_types.\n{generated}\n"
    );
    let output = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../../../packages/lexical-conformance/diff/host-packet.generated.ts");
    let mut formatter = Command::new("bunx")
        .args(["--bun", "@biomejs/biome", "format", "--stdin-file-path"])
        .arg(&output)
        .current_dir(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../../apps/web"))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .map_err(rootcause::Report::new)?;
    formatter
        .stdin
        .take()
        .expect("formatter stdin")
        .write_all(generated.as_bytes())
        .map_err(rootcause::Report::new)?;
    let formatted = formatter
        .wait_with_output()
        .map_err(rootcause::Report::new)?;
    if !formatted.status.success() {
        return Err(rootcause::report!(
            "formatting host packet declarations failed"
        ));
    }
    let generated = String::from_utf8(formatted.stdout).map_err(rootcause::Report::new)?;
    if args.check {
        let current = std::fs::read_to_string(output).map_err(rootcause::Report::new)?;
        if current != generated {
            return Err(rootcause::report!("host packet declarations are stale"));
        }
    } else {
        std::fs::write(output, generated).map_err(rootcause::Report::new)?;
    }
    Ok(())
}
