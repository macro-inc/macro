use super::*;

fn image() -> GuestImage {
    GuestImage::try_new("macro-box/2026-11-10").unwrap()
}

fn updating(start: bool) -> Phase {
    Phase::Updating { host: HOST, start }
}

#[test]
fn image_updates() {
    check(vec![
        Case {
            name: "a running computer stops, rebuilds and starts again",
            phase: Phase::Running { host: HOST },
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: true,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::UpdateImage { image: image() },
            host_has_room: true,
            expected_phase: updating(true),
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![Effect::Rebuild {
                host: HOST,
                image: image(),
                start: true,
            }],
        },
        Case {
            name: "a stopped computer rebuilds and stays off",
            phase: Phase::Stopped { host: HOST },
            power: Power::Off,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::UpdateImage { image: image() },
            host_has_room: true,
            expected_phase: updating(false),
            expected_power: Power::Off,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![Effect::Rebuild {
                host: HOST,
                image: image(),
                start: false,
            }],
        },
        Case {
            name: "a booting computer is not updated",
            phase: Phase::Booting { host: HOST },
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::UpdateImage { image: image() },
            host_has_room: true,
            expected_phase: Phase::Booting { host: HOST },
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![],
        },
        Case {
            name: "an updating computer ignores a second update",
            phase: updating(true),
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::UpdateImage { image: image() },
            host_has_room: true,
            expected_phase: updating(true),
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![],
        },
        Case {
            name: "a failed computer is not updated",
            phase: Phase::Failed { host: HOST },
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::UpdateImage { image: image() },
            host_has_room: true,
            expected_phase: Phase::Failed { host: HOST },
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![],
        },
        Case {
            name: "the rebuilt guest boots and waits for macrod",
            phase: updating(true),
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::InstanceStarted,
            host_has_room: true,
            expected_phase: Phase::Booting { host: HOST },
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![Effect::ScheduleTimer {
                kind: TimerKind::MacrodMissing,
                at: now() + MACROD_GRACE,
            }],
        },
        Case {
            name: "macrod back before the rebuild completes makes it running",
            phase: updating(true),
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: true,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::InstanceStarted,
            host_has_room: true,
            expected_phase: Phase::Running { host: HOST },
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![],
        },
        Case {
            name: "turned off during the rebuild, the started guest stops",
            phase: updating(true),
            power: Power::Off,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::InstanceStarted,
            host_has_room: true,
            expected_phase: Phase::Stopping { host: HOST },
            expected_power: Power::Off,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![Effect::Stop { host: HOST }],
        },
        Case {
            name: "the rebuilt stopped guest is stopped",
            phase: updating(false),
            power: Power::Off,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::InstanceStopped,
            host_has_room: true,
            expected_phase: Phase::Stopped { host: HOST },
            expected_power: Power::Off,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![],
        },
        Case {
            name: "power on during a stopped rebuild waits for it",
            phase: updating(false),
            power: Power::Off,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::PowerOn,
            host_has_room: true,
            expected_phase: updating(false),
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: true,
            expected_effects: vec![],
        },
        Case {
            name: "a waiting power on starts once the rebuild stops",
            phase: updating(false),
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: true,
            event: Event::InstanceStopped,
            host_has_room: true,
            expected_phase: Phase::Stopped { host: HOST },
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: true,
            expected_effects: vec![Effect::ScheduleTimer {
                kind: TimerKind::PowerOnRetry,
                at: now() + POWER_ON_RETRY,
            }],
        },
        Case {
            name: "the guest going down during the rebuild is not a crash",
            phase: updating(true),
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::MacrodMissing {
                instance_status: Some(InstanceStatus::Stopped),
            },
            host_has_room: true,
            expected_phase: updating(true),
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![],
        },
        Case {
            name: "release during the rebuild destroys the guest and its data disk",
            phase: updating(true),
            power: Power::On,
            billing: Billing::Active,
            macrod_connected: false,
            recent_crashes: vec![],
            power_on_requested: false,
            event: Event::ReleaseNow,
            host_has_room: true,
            expected_phase: Phase::Destroyed,
            expected_power: Power::On,
            expected_billing: Billing::Active,
            expected_power_on_requested: false,
            expected_effects: vec![
                Effect::RemoveBillingItem,
                Effect::Destroy { host: HOST },
                Effect::RevokeHarness,
            ],
        },
    ]);
}
