#!/usr/bin/env bash
# Regenerates spec/openapi.json and src/generated.rs from spec/rest-api.yaml.
# Bump INCUS_VERSION with the nixpkgs incus-lts version, then run this script.
set -euo pipefail

INCUS_VERSION="7.0.1"
PROGENITOR_VERSION="0.15.1"

if [[ -z "${IN_NIX_SHELL:-}" ]]; then
  echo "Run inside the pinned dev shell: nix develop --command crates/incus_client/regen.sh $*" >&2
  exit 1
fi

for tool in swagger2openapi cargo rustfmt python3 curl; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "Missing $tool; re-enter the pinned dev shell with nix develop." >&2
    exit 1
  fi
done

crate_dir="$(\cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
work_dir="$(mktemp -d "${TMPDIR:-/tmp}/incus-client-regen.XXXXXX")"
trap 'rm -rf "$work_dir"' EXIT

if [[ "${1:-}" == "--fetch" ]]; then
  curl -fsSL -o "$crate_dir/spec/rest-api.yaml" \
    "https://raw.githubusercontent.com/lxc/incus/v${INCUS_VERSION}/doc/rest-api.yaml"
fi

# --warnOnly tolerates operations Swagger 2 declares with two body parameters
# (a JSON request or a raw upload); the patch keeps only the JSON one.
swagger2openapi --patch --warnOnly -o "$work_dir/converted.json" \
  "$crate_dir/spec/rest-api.yaml"
python3 "$crate_dir/spec/patch.py" "$work_dir/converted.json" "$crate_dir/spec/openapi.json"

mkdir -p "$work_dir/generator/src"
cat >"$work_dir/generator/Cargo.toml" <<EOF
[package]
name = "incus_client_generator"
version = "0.0.0"
edition = "2024"
publish = false

[workspace]

[dependencies]
openapiv3 = "=2.2.0"
prettyplease = "0.2"
progenitor = "=${PROGENITOR_VERSION}"
serde_json = "1"
syn = { version = "2", features = ["visit-mut"] }
EOF

cat >"$work_dir/generator/src/main.rs" <<'EOF'
use std::fs::File;
use syn::visit_mut::VisitMut;

struct LineDocComments;

impl VisitMut for LineDocComments {
    fn visit_attributes_mut(&mut self, attributes: &mut Vec<syn::Attribute>) {
        let mut normalized = Vec::new();
        for attribute in attributes.drain(..) {
            if let syn::Meta::NameValue(meta) = &attribute.meta
                && meta.path.is_ident("doc")
                && let syn::Expr::Lit(expression) = &meta.value
                && let syn::Lit::Str(documentation) = &expression.lit
            {
                // Multiline attributes become indented block comments in
                // prettyplease; rustdoc reads their paragraphs as Rust code.
                for line in documentation.value().lines() {
                    normalized.push(syn::parse_quote!(#[doc = #line]));
                }
            } else {
                normalized.push(attribute);
            }
        }
        *attributes = normalized;
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut arguments = std::env::args().skip(1);
    let input = arguments.next().ok_or("missing input path")?;
    let output = arguments.next().ok_or("missing output path")?;

    let spec: openapiv3::OpenAPI = serde_json::from_reader(File::open(input)?)?;

    let mut settings = progenitor::GenerationSettings::default();
    settings
        .with_interface(progenitor::InterfaceStyle::Positional)
        .with_map_type("::std::collections::BTreeMap");

    let mut generator = progenitor::Generator::new(&settings);
    let tokens = generator.generate_tokens(&spec)?;
    let mut file: syn::File = syn::parse2(tokens)?;
    LineDocComments.visit_file_mut(&mut file);

    let header = "// @generated by crates/incus_client/regen.sh from spec/openapi.json. Do not edit.\n";
    std::fs::write(output, format!("{header}{}", prettyplease::unparse(&file)))?;
    Ok(())
}
EOF

# A target dir of its own, kept between runs so regeneration is incremental.
CARGO_TARGET_DIR="$crate_dir/../../target/incus_client_regen" cargo run --quiet \
  --manifest-path "$work_dir/generator/Cargo.toml" -- \
  "$crate_dir/spec/openapi.json" "$crate_dir/src/generated.rs"

rustfmt --edition 2024 "$crate_dir/src/generated.rs"
