import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildWasm, root } from '../../lexical-conformance/diff/build-wasm';
import { inventoryHooks, type Source } from './hook-inventory';

const upstream = path.join(root, 'target/lexical-upstream');
const pin: { version: string; sha256: string } = JSON.parse(
  readFileSync(
    path.join(root, 'packages/lexical-conformance/upstream.lock'),
    'utf8'
  )
);
const patch = createHash('sha256')
  .update(
    readFileSync(
      path.join(root, 'packages/lexical-conformance/record/hooks.patch')
    )
  )
  .digest('hex');
if (
  pin.version !== '0.45.0' ||
  readFileSync(path.join(upstream, '.recorder-pin'), 'utf8') !==
    pin.sha256 + patch
)
  throw new Error(
    'prepare the checksum-pinned conformance upstream sources first'
  );
const sources: Source[] = [];
function visit(directory: string): void {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === '__tests__' || entry.name === 'node_modules') continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) visit(file);
    else if (/\.tsx?$/.test(entry.name) && !entry.name.endsWith('.d.ts'))
      sources.push({
        path: path.relative(upstream, file),
        text: readFileSync(file, 'utf8'),
      });
  }
}
visit(path.join(upstream, 'packages'));
const hooks = inventoryHooks(sources);
buildWasm();
const wasm = await import(
  '../../lexical-conformance/pkg/node/lexical_conformance_wasm'
);
if (wasm.upstream_version() !== '0.45.0')
  throw new Error('unexpected model upstream version');
const names: unknown = wasm.foreign_hook_index();
if (!Array.isArray(names) || !names.every((name) => typeof name === 'string'))
  throw new Error('invalid model hook index');
const derived = hooks.map((hook) => hook.name).sort();
if (JSON.stringify(derived) !== JSON.stringify([...names].sort()))
  throw new Error(`hook mismatch\nupstream: ${derived}\nmodel: ${names}`);
const ordered = names.map((name) => {
  const hook = hooks.find((hook) => hook.name === name);
  if (hook === undefined) throw new Error(`missing upstream hook: ${name}`);
  // One caller/override location makes the committed output reviewable without
  // vendoring every repeated use; the scanner checks the complete source set.
  return {
    name: hook.name,
    static: hook.static,
    caller: hook.calls[0] ?? null,
    override: hook.overrides[0] ?? null,
  };
});
const unformatted = `// Generated by scripts/derive-hooks.ts against Lexical v0.45.0.\n// Do not edit: order is checked against the model-derived ForeignHook enum.\nexport const foreignHooks = ${JSON.stringify(ordered, null, 2)} as const;\n`;
const destination = fileURLToPath(
  new URL('../src/hooks.generated.ts', import.meta.url)
);
const formatted = spawnSync(
  'bunx',
  ['biome', 'format', '--stdin-file-path', destination],
  {
    cwd: path.join(root, 'apps/web'),
    encoding: 'utf8',
    input: unformatted,
  }
);
if (formatted.error) throw formatted.error;
if (formatted.status !== 0) throw new Error(formatted.stderr);
const output = formatted.stdout;
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output)
    throw new Error('stale generated hook inventory');
} else writeFileSync(destination, output);
console.log(
  `derived ${ordered.length} foreign hooks from ${sources.filter((source) => source.path.includes('/src/')).length} source files`
);
