import { readdir, readFile } from 'node:fs/promises';
import { join, posix } from 'node:path';

/** Keep canonical plugin output intact; only organize pages for the agent's reader. */
export async function readMarkdownPages(directory: string) {
  const pages = new Map<string, string>();
  for (const entry of (await readdir(directory, { recursive: true })).sort()) {
    if (entry.endsWith('.md')) {
      pages.set(
        entry.replaceAll('\\', '/'),
        await readFile(join(directory, entry), 'utf8')
      );
    }
  }
  return pages;
}

export function packageEntityDocs(
  sourcePages: ReadonlyMap<string, string>,
  descriptions: Readonly<Record<string, string>>
) {
  // The public SDK retains deployed legacy APIs. Native discovery tools cover
  // current sessions; omit the legacy chat and workspace namespaces here.
  const hiddenNamespace = (path: string) =>
    /^src\/entities\/(chats|workspace)\//.test(path);
  const pages = new Map(
    [...sourcePages]
      .filter(([path]) => !hiddenNamespace(path))
      .map(([path, markdown]) => [
        path,
        markdown
          .replace(
            /^### (?:chats|workspace)\b[^\n]*\n[\s\S]*?(?=^### |(?![\s\S]))/gm,
            ''
          )
          .replace(/^\| <a id="property-(?:chats|workspace)"[^\n]*\n/gm, ''),
      ])
  );
  const core = [
    'src/macro/',
    'src/config/',
    'src/mentions/',
    'src/entities/entity/',
    'src/entities/search/',
    'src/entities/sharing/',
    'src/entities/messages/',
    'src/entities/reference/',
    'src/utils/',
    'src/events/',
  ];
  const sections = [
    ...Object.entries(descriptions).map(([directory, description]) => ({
      name:
        directory === 'foreign'
          ? 'foreignEntities'
          : directory.replace(/-([a-z])/g, (_, letter: string) =>
              letter.toUpperCase()
            ),
      description,
      // Agent and host setup share one discovery topic, keeping the classifier
      // request within its 32-question contract as the public API grows.
      prefixes: (directory === 'agents'
        ? ['agents', 'harnesses']
        : [directory]
      ).map((value) => `src/entities/${value}/`),
    })),
    {
      name: 'core',
      description:
        'SDK construction, entity handles, lazy fields, search options, events and shared types.',
      prefixes: core,
    },
  ];
  return sections.map(({ name, description, prefixes }) => {
    const included = new Set(
      [...pages.keys()].filter(
        (path) =>
          !path.endsWith('/README.md') &&
          prefixes.some((prefix) => path.startsWith(prefix))
      )
    );
    if (!included.size)
      throw new Error(`TypeDoc generated no pages for ${name}`);
    // Follow the plugin's links, not TypeScript syntax. Shared wire definitions
    // may recurse or reference one another; a Set handles cycles deterministically.
    for (const path of included) {
      const markdown = pages.get(path);
      if (markdown === undefined)
        throw new Error(`Missing TypeDoc page: ${path}`);
      for (const match of markdown.matchAll(/\]\(([^)]+\.md)(?:#[^)]*)?\)/g)) {
        const target = posix.normalize(
          posix.join(posix.dirname(path), decodeURIComponent(match[1] ?? ''))
        );
        if (hiddenNamespace(target)) continue;
        if (!pages.has(target))
          throw new Error(`Broken TypeDoc link: ${path} -> ${target}`);
        if (target.startsWith('generated/')) included.add(target);
      }
    }
    const overviewPages = new Set(
      [...included].filter((path) =>
        name === 'core'
          ? path.startsWith('src/macro/') || path.startsWith('src/config/')
          : path.includes('/namespace/')
      )
    );
    // Namespace signatures are not usable without their local options and enums.
    // Follow those TypeDoc links, while leaving entity classes and large wire
    // contracts in the full reference available through explicit discovery.
    for (const path of overviewPages) {
      for (const match of (pages.get(path) ?? '').matchAll(
        /\]\(([^)]+\.md)(?:#[^)]*)?\)/g
      )) {
        const target = posix.normalize(
          posix.join(posix.dirname(path), decodeURIComponent(match[1] ?? ''))
        );
        if (
          prefixes.some((prefix) => target.startsWith(prefix)) &&
          (target.includes('/type-aliases/') ||
            target.includes('/interfaces/')) &&
          pages.has(target)
        )
          overviewPages.add(target);
      }
    }
    if (!overviewPages.size)
      throw new Error(`TypeDoc generated no namespace overview for ${name}`);
    return {
      name,
      description,
      overview: [...overviewPages]
        .sort()
        .map((path) => `<!-- ${path} -->\n${pages.get(path)}`)
        .join('\n\n'),
      documentation: [
        `# Macro SDK: ${name}`,
        'Generated by TypeDoc. Paths below refer to the canonical Markdown hierarchy. Other entity handles are documented in their named section; request core for shared SDK helpers.',
        ...[...included]
          .sort()
          .map((path) => `<!-- ${path} -->\n${pages.get(path)}`),
      ].join('\n\n'),
    };
  });
}
