/**
 * Build the code-mode assets the Rust crates embed: the Deno SDK and Handlebars
 * bundles, the agent documentation catalog and the operation labels.
 *
 * Usage: bun scripts/generate.ts <output-directory>
 */

import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderSdkDocs } from '@macro-inc/sdk-docs/render';
import { entityDirectories } from './catalog';
import { packageEntityDocs, readMarkdownPages } from './typedoc';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const [outputArgument] = Bun.argv.slice(2);
if (!outputArgument)
  throw new Error('usage: bun scripts/generate.ts <output-directory>');
const outputDirectory = resolve(outputArgument);

// Without its own install, the SDK's imports resolve to the root workspace's
// versions of the same packages and the bundle silently differs.
if (!existsSync(join(root, 'packages/sdk/node_modules')))
  throw new Error(
    'packages/sdk/node_modules is missing; run `bun install --frozen-lockfile` in packages/sdk.'
  );

await mkdir(outputDirectory, { recursive: true });

async function artifact(name: string, output: string) {
  await Bun.write(join(outputDirectory, name), output);
}

// Each is its own module in the sandbox's import map, so `sdk.mjs` and the
// program import one instance, as Lexical's `$` functions require.
const lexicalSpecifiers = [
  'lexical',
  ...[
    'code',
    'headless',
    'link',
    'list',
    'mark',
    'markdown',
    'rich-text',
    'table',
    'utils',
  ].map((name) => `@lexical/${name}`),
];
const lexicalExternals = [...lexicalSpecifiers, '@macro-inc/sdk/lexical'];

for (const [entry, name] of [
  ['packages/code-mode-sdk/src/index.ts', 'sdk'],
  ['node_modules/handlebars/dist/handlebars.js', 'handlebars'],
]) {
  const result = await Bun.build({
    entrypoints: [`${root}${entry}`],
    target: 'browser',
    format: 'esm',
    minify: true,
    define: { 'process.env': '{}' },
    external: lexicalExternals,
    plugins: [
      {
        name: 'explicit-service-hosts',
        setup(build) {
          // Runtime hosts are supplied explicitly. Local git/portmap discovery is
          // a CLI convenience and must not pull subprocess/filesystem code into Deno.
          build.onLoad({ filter: /\/sdk\/src\/local-portmap\.ts$/ }, () => ({
            contents:
              'export function resolveLocalPortmap() { return undefined; }',
            loader: 'js',
          }));
        },
      },
    ],
  });
  if (!result.success)
    throw new AggregateError(result.logs, 'SDK build failed');
  const output = result.outputs[0];
  if (!output) throw new Error('No bundle produced');
  await artifact(
    `${name}.mjs`,
    `// Generated by packages/code-mode-sdk/scripts/generate.ts.\n${await output.text()}`
  );
}

// Lexical, the `@lexical/*` packages and `@macro-inc/sdk/lexical`, code split
// so they share chunks, in `lexical/`. `lexical-modules.tsv` lists every file
// with the specifier it serves (empty for a chunk); runs that never import
// them pay only the file writes. Lexical's development builds keep readable
// error messages, which an agent needs to fix its program.
const lexicalCondition = 'development';
const sdkModules = join(root, 'packages/sdk/node_modules');
const lexicalEntries = new Map<string, string>();
for (const specifier of lexicalSpecifiers) {
  const manifest = await Bun.file(
    join(sdkModules, specifier, 'package.json')
  ).json();
  const file = manifest.exports?.['.']?.import?.[lexicalCondition];
  if (typeof file !== 'string')
    throw new Error(`${specifier} has no ${lexicalCondition} ES module export`);
  lexicalEntries.set(specifier, join(sdkModules, specifier, file));
}
lexicalEntries.set(
  '@macro-inc/sdk/lexical',
  join(root, 'packages/sdk/src/lexical.ts')
);
const lexicalBuild = await Bun.build({
  entrypoints: [...lexicalEntries.values()],
  target: 'browser',
  format: 'esm',
  minify: true,
  splitting: true,
  conditions: [lexicalCondition],
  define: { 'process.env': '{}' },
  naming: { entry: '[name].[ext]', chunk: 'chunk-[hash].[ext]' },
});
if (!lexicalBuild.success)
  throw new AggregateError(lexicalBuild.logs, 'Lexical build failed');
const lexicalFiles = new Map<string, string>();
for (const output of lexicalBuild.outputs)
  lexicalFiles.set(
    join('lexical', output.path.replace(/^\.\//, '')),
    await output.text()
  );
const lexicalSpecifierByFile = new Map<string, string>();
for (const [specifier, entry] of lexicalEntries) {
  const file = join('lexical', basename(entry).replace(/\.(mjs|js|ts)$/, '.js'));
  if (!lexicalFiles.has(file))
    throw new Error(`No Lexical module produced for ${specifier} (${file})`);
  lexicalSpecifierByFile.set(file, specifier);
}
await mkdir(join(outputDirectory, 'lexical'), { recursive: true });
for (const [file, contents] of lexicalFiles) await artifact(file, contents);
await artifact(
  'lexical-modules.tsv',
  [...lexicalFiles.keys()]
    .sort()
    .map((file) => `${file}\t${lexicalSpecifierByFile.get(file) ?? ''}\n`)
    .join('')
);

const rendered = await mkdtemp(join(outputDirectory, '.docs-'));
try {
  const notes = await renderSdkDocs(root, rendered);
  const pages = await readMarkdownPages(join(rendered, 'markdown'));
  const docs = packageEntityDocs(pages, entityDirectories, notes);
  await artifact('documentation.json', `${JSON.stringify(docs, null, 2)}\n`);
} finally {
  await rm(rendered, { recursive: true, force: true });
}

// The registry comes from generated SDK classes, not hand-maintained endpoint paths.
const operations: Record<string, string> = {};
const labels: Record<string, string> = {
  'cognition.decisions': 'Classify content',
  'cognition.structuredCompletion': 'Generate structured content',
  'storage.postItemsSoupAst': 'Browse workspace',
  'search.unifiedSearch': 'Search workspace',
  'search.simpleUnifiedSearch': 'Search workspace',
  'storage.getDocument': 'Read document',
  'storage.getUserDocumentsHandler': 'List documents',
  'storage.postItemsSoupAstGrouped': 'Browse workspace',
};
for (const [service, directory] of Object.entries({
  'agent-harness': 'agent-harness',
  auth: 'auth',
  calendar: 'calendar',
  cognition: 'cognition',
  contacts: 'contacts',
  email: 'email',
  notification: 'notification',
  properties: 'properties',
  search: 'search',
  'scheduled-action': 'scheduled-action',
  unfurl: 'unfurl',
  storage: 'storage',
})) {
  const { Sdk } = await import(
    `${root}packages/sdk/generated/${directory}/sdk.gen.ts`
  );
  for (const name of Object.getOwnPropertyNames(Sdk.prototype)) {
    if (name === 'constructor') continue;
    operations[`${service}.${name}`] =
      labels[`${service}.${name}`] ??
      name
        .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
        .replace(/Handler$/, '')
        .replace(/^./, (letter: string) => letter.toUpperCase())
        .trim();
  }
}
await artifact('operations.json', `${JSON.stringify(operations, null, 2)}\n`);
