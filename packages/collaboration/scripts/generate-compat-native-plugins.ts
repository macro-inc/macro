import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import ts from 'typescript';

interface Transformer {
  readonly name: string;
  readonly variant: string;
}

/** Read the source-generated Rust identities without inventing a second catalog. */
export function parseShortcutIdentities(
  source: string
): readonly Transformer[] {
  const declaration = 'pub enum ShortcutTransformerId {';
  const start = source.indexOf(declaration);
  const end = source.indexOf('\n}', start);
  if (start < 0 || end < 0 || source.indexOf(declaration, start + 1) >= 0)
    throw new Error('Expected one source ShortcutTransformerId enum');
  const body = source
    .slice(start + declaration.length, end)
    .replace(/^\s*\/\/\/[^\n]*(?:\n|$)/gm, '');
  const entry =
    /\s*#\[serde\(rename = "([A-Z][A-Z0-9_]*)"\)\]\s*#\[strum\(serialize = "([A-Z][A-Z0-9_]*)"\)\]\s*([A-Za-z][A-Za-z0-9_]*),/y;
  const names = new Set<string>();
  const variants = new Set<string>();
  const result: Transformer[] = [];
  let position = 0;
  while (body.slice(position).trim().length > 0) {
    entry.lastIndex = position;
    const match = entry.exec(body);
    if (match === null)
      throw new Error('Unsupported transformer identity declaration');
    const [, name, serialized, variant] = match;
    if (
      !name ||
      !variant ||
      name !== serialized ||
      variant === 'Unknown' ||
      names.has(name) ||
      variants.has(variant)
    )
      throw new Error('Duplicate or inconsistent transformer identity');
    names.add(name);
    variants.add(variant);
    result.push({ name, variant });
    position = entry.lastIndex;
  }
  if (result.length === 0 || result.length > 65534)
    throw new Error('Invalid transformer catalog size');
  return result;
}

/** Bebop may normalize acronym spelling; read its actual emitted symbols. */
export function parseEmittedTransformerSymbols(
  source: string
): ReadonlyMap<number, string> {
  const file = ts.createSourceFile(
    'compatibility.generated.ts',
    source,
    ts.ScriptTarget.Latest,
    true
  );
  const declarations = file.statements.filter(
    (statement) =>
      ts.isEnumDeclaration(statement) &&
      statement.name.text === 'CompatShortcutTransformer'
  );
  if (declarations.length !== 1)
    throw new Error('Expected one emitted transformer enum');
  const declaration = declarations[0];
  if (!ts.isEnumDeclaration(declaration))
    throw new Error('Invalid transformer enum');
  const result = new Map<number, string>();
  for (const member of declaration.members) {
    if (
      !ts.isIdentifier(member.name) ||
      !member.initializer ||
      !ts.isNumericLiteral(member.initializer)
    )
      throw new Error('Unexpected emitted transformer identity');
    const value = Number(member.initializer.text);
    if (!Number.isInteger(value) || value < 0 || result.has(value))
      throw new Error('Invalid emitted transformer numeric ID');
    result.set(value, member.name.text);
  }
  if (result.get(0) !== 'Unknown')
    throw new Error('Transformer zero must remain unknown');
  return result;
}

export function generateNativePluginSchema(
  source: string,
  symbols?: ReadonlyMap<number, string>
): {
  readonly schema: string;
  readonly typescript: string | undefined;
} {
  const identities = parseShortcutIdentities(source);
  const hash = createHash('sha256').update(source).digest('hex');
  const header = `// Generated by generate-compat-native-plugins.ts. Do not edit.\n// ShortcutTransformerId source SHA256 ${hash}\n`;
  return {
    schema: `${header}
enum CompatNativePlugin : byte { Unknown = 0; MarkdownShortcuts = 1; }
enum CompatShortcutTransformer : uint16 {
  Unknown = 0;
${identities.map(({ variant }, index) => `  ${variant} = ${index + 1};`).join('\n')}
}
union CompatNativePluginConfig {
  1 -> struct CompatMarkdownShortcutsPlugin {
    CompatShortcutTransformer[] typing;
    CompatShortcutTransformer[] enter;
  }
}
`,
    typescript:
      symbols === undefined
        ? undefined
        : `${header}import { CompatShortcutTransformer } from './compatibility.generated';

const ids = new Map<string, CompatShortcutTransformer>([
${identities
  .map(({ name }, index) => {
    const symbol = symbols.get(index + 1);
    if (symbol === undefined || symbols.size !== identities.length + 1)
      throw new Error(
        'Regenerate the compatibility schema before its name converter'
      );
    return `  [${JSON.stringify(name)}, CompatShortcutTransformer.${symbol}],`;
  })
  .join('\n')}
]);

/** Source names come from the plugin-local object identity lookup. */
export function nativeShortcutTransformerId(name: string): CompatShortcutTransformer {
  const id = ids.get(name);
  if (id === undefined) throw new Error('Unknown native shortcut transformer');
  return id;
}
`,
  };
}

if (import.meta.main) {
  const root = resolve(import.meta.dirname, '../../..');
  const input = resolve(
    root,
    'crates/client/lexical/macro_document_model/src/plugins_group_a/shortcuts/transformer_ids.rs'
  );
  const symbols = process.argv.includes('--schema-only')
    ? undefined
    : parseEmittedTransformerSymbols(
        readFileSync(
          resolve(
            root,
            'packages/collaboration/src/session/compatibility.generated.ts'
          ),
          'utf8'
        )
      );
  const generated = generateNativePluginSchema(
    readFileSync(input, 'utf8'),
    symbols
  );
  const outputs = {
    schema: generated.schema,
    typescript:
      generated.typescript === undefined
        ? undefined
        : execFileSync(
            resolve(root, 'node_modules/.bin/biome'),
            [
              'format',
              '--stdin-file-path',
              resolve(
                root,
                'packages/collaboration/src/session/compatibility-native-plugins.generated.ts'
              ),
            ],
            {
              input: generated.typescript,
              cwd: resolve(root, 'packages/collaboration'),
            }
          ).toString(),
  };
  for (const [file, content] of [
    [
      'crates/client/document_session_wasm/abi/compatibility-native-plugins.bop',
      outputs.schema,
    ],
    [
      'packages/collaboration/src/session/compatibility-native-plugins.generated.ts',
      outputs.typescript,
    ],
  ]) {
    if (content === undefined) continue;
    const destination = resolve(root, file);
    if (process.argv.includes('--check')) {
      if (readFileSync(destination, 'utf8') !== content)
        throw new Error(`Native plugin schema drift: ${file}`);
    } else writeFileSync(destination, content);
  }
}
