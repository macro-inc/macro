/**
 * Write the OCaml client from the OpenAPI specs (packages/sdk/specs/*.json):
 * `lib/macro_<service>.ml(i)` per service, `lib/macro.ml(i)` (the `Macro`
 * module: `Json`, `Error` and one submodule per service),
 * `lib/operations.json`, and the test fixtures
 * `test/all_operations_calls.ml` and `test/all_operations.json`.
 *
 * Usage, from packages/sdk-ocaml: bun generator/generate.ts
 *
 * Every operation gets a function; generation fails on any it can't emit.
 */

import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  type CallFixture,
  emitService,
  emptyStats,
  MACRO_MLI_PRELUDE,
  type OperationEntry,
} from './emit';
import { loadClassification, loadSpecs, operations } from './spec';

const root = fileURLToPath(new URL('../', import.meta.url));
const started = performance.now();

const specs = loadSpecs();
const all = operations(specs);
const classification = loadClassification();
const stats = emptyStats();

const banner =
  '(* Generated by packages/sdk-ocaml/generator from packages/sdk/specs. Do not edit. *)\n';
const units: { unitName: string; module: string }[] = [];
const entries: OperationEntry[] = [];
const calls: string[] = [];
const fixtures: CallFixture[] = [];

mkdirSync(`${root}lib`, { recursive: true });
for (const file of readdirSync(`${root}lib`))
  if (
    /^macro_.*\.mli?$/.test(file) &&
    !/^macro_(runtime|json|error)\.ml$/.test(file)
  )
    rmSync(`${root}lib/${file}`);

for (const { service, spec } of specs) {
  const out = emitService(
    service,
    spec,
    all.filter((op) => op.service === service),
    classification,
    stats
  );
  writeFileSync(`${root}lib/${out.unitName}.ml`, out.ml);
  writeFileSync(`${root}lib/${out.unitName}.mli`, out.mli);
  units.push(out);
  entries.push(...out.entries);
  calls.push(...out.calls);
  fixtures.push(...out.fixtures);
}

if (entries.length !== all.length)
  throw new Error(`emitted ${entries.length} operations for ${all.length}`);

const macroMl = `${banner}
module Json = Macro_json

exception Error = Macro_error.Error
${units.map(({ unitName, module }) => `\nmodule ${module} = ${capitalize(unitName)}\n`).join('')}`;
const macroMli = `${banner}
${MACRO_MLI_PRELUDE}${units
  .map(
    ({ unitName, module }) =>
      `\nmodule ${module} : module type of ${capitalize(unitName)}\n`
  )
  .join('')}`;
writeFileSync(`${root}lib/macro.ml`, macroMl);
writeFileSync(`${root}lib/macro.mli`, macroMli);
writeFileSync(
  `${root}lib/operations.json`,
  `${JSON.stringify({ operations: entries }, null, 2)}\n`
);

mkdirSync(`${root}test`, { recursive: true });
writeFileSync(
  `${root}test/all_operations_calls.ml`,
  `(* Generated by packages/sdk-ocaml/generator: every operation called with
   sample arguments (required ones only, then all of them), in the order of
   test/all_operations.json. Do not edit. *)

let calls : (string * (unit -> unit)) list =
  [
${calls.join('')}  ]
`
);
writeFileSync(
  `${root}test/all_operations.json`,
  `${JSON.stringify(fixtures)}\n`
);

function capitalize(name: string) {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

const bytes = units.reduce(
  (total, { unitName }) =>
    total +
    Bun.file(`${root}lib/${unitName}.ml`).size +
    Bun.file(`${root}lib/${unitName}.mli`).size,
  Bun.file(`${root}lib/macro.mli`).size
);
console.log(
  [
    `${entries.length} operations from ${specs.length} specs in ${Math.round(performance.now() - started)} ms; ${(bytes / 1e6).toFixed(1)} MB of OCaml`,
    `${stats.types} OCaml types (${stats.records} records)`,
    `request bodies: ${stats.bodies.total} (${stats.bodies.typed} typed, ${stats.bodies.json} Macro.Json.t, ${stats.bodies.text} string, ${stats.bodies.multipart} multipart)`,
    ...stats.bodies.untyped.map((line) => `  ${line}`),
    `parameters: ${stats.parameters.total} (${stats.parameters.typed} typed, ${stats.parameters.json} Macro.Json.t)`,
    `responses: ${stats.responses.total} (${stats.responses.typed} typed, ${stats.responses.json} Macro.Json.t, ${stats.responses.text} string, ${stats.responses.unit} unit, ${stats.responses.byStatus} by status)`,
    ...stats.responses.untyped.map((line) => `  ${line}`),
    `unions typed Macro.Json.t (not reliably decodable): ${stats.unionFallbacks.length}`,
    ...stats.unionFallbacks.map((line) => `  ${line}`),
    `schemas that allow any value ({}, an object without properties, an array without items), typed Macro.Json.t: ${stats.openSchemas}`,
  ].join('\n')
);
