(* macro_sdk_gen: generate the OCaml SDK from the OpenAPI specs.

   sdk   --specs DIR --out DIR --format-as DIR [--main NAME] [--untyped FILE]
         one .ml/.mli per spec, the library main module and the untyped-site list
   cases --specs DIR --out DIR --library NAME --format-as DIR
         cases.ml: every operation with sample arguments, for the tests

   [--format-as] is a directory inside the package: ocamlformat reads the
   package's .ocamlformat from there, wherever the output goes. *)

open Ppxlib
open Syntax

let usage () =
  prerr_endline
    "usage: macro_sdk_gen (sdk|cases) --specs DIR --out DIR --format-as DIR \
     [--library NAME] [--main NAME]";
  exit 2

let option args key =
  let rec find = function
    | k :: v :: _ when k = key -> Some v
    | _ :: rest -> find rest
    | [] -> None
  in
  find args

let required args key =
  match option args key with Some v -> v | None -> usage ()

let spec_files dir =
  Sys.readdir dir |> Array.to_list
  |> List.filter (fun f -> Filename.check_suffix f ".json")
  |> List.sort compare
  |> List.map (Filename.concat dir)

let load file =
  try Lower_ops.service (Spec.load file)
  with Spec.Unsupported { at; message } ->
    Printf.eprintf "%s: %s: cannot generate %s\n" file at message;
    exit 1

(* Operation functions and codecs share one namespace; refuse to emit two
   values with the same name. *)
let check_names (service : Ir.service) =
  let values = Naming.namespace () in
  List.iter
    (fun (op : Ir.operation) ->
      Naming.claim values op.fn_name ~what:("operation " ^ op.operation_id))
    service.operations;
  List.iter
    (fun (def : Ir.def) ->
      List.iter
        (fun v -> Naming.claim values v ~what:("codec for " ^ def.name))
        (Emit_types.value_names def))
    service.defs

let file_name module_name = String.uncapitalize_ascii module_name

let write ~format_as ~out file contents =
  Print.write
    ~name:(Filename.concat format_as file)
    ~path:(Filename.concat out file) contents

let module_alias name target =
  B.pstr_module
    (B.module_binding ~name:(Syntax.name (Some name))
       ~expr:(B.pmod_ident (lid target)))

(* The library's main module: the runtime's public modules and one module per service. *)
let main_module services =
  let runtime =
    List.map
      (fun m -> module_alias m ("Macro_sdk_runtime." ^ m))
      [ "Json"; "Config"; "Error"; "Request" ]
  in
  runtime
  @ List.map
      (fun (s : Ir.service) -> module_alias s.module_name s.module_name)
      services

let sdk args =
  let specs = required args "--specs"
  and out = required args "--out"
  and format_as = required args "--format-as" in
  let services = List.map load (spec_files specs) in
  List.iter check_names services;
  let total_ops = ref 0 and untyped = Buffer.create 4096 in
  List.iter
    (fun (service : Ir.service) ->
      let header = Print.header (service.spec_name ^ ".json") in
      let prelude =
        [%str
          module Json = Macro_sdk_runtime.Json
          module Request = Macro_sdk_runtime.Request]
      in
      let structure =
        prelude @ Emit_types.structure service.defs @ Emit_ops.structure service
      in
      let signature =
        Emit_types.signature service.defs @ Emit_ops.signature service
      in
      let base = file_name service.module_name in
      write ~format_as ~out (base ^ ".ml") (Print.structure ~header structure);
      write ~format_as ~out (base ^ ".mli") (Print.signature ~header signature);
      total_ops := !total_ops + List.length service.operations;
      List.iter
        (fun (at, reason) ->
          Printf.bprintf untyped "%s.json %s: %s\n" service.spec_name at reason)
        service.untyped;
      Printf.printf "%-18s %4d operations %5d types %4d untyped\n"
        service.spec_name
        (List.length service.operations)
        (List.length service.defs)
        (List.length service.untyped))
    services;
  (match option args "--main" with
  | Some main ->
      let header =
        "(* Generated by packages/sdk-ocaml/gen. Do not edit. *)\n\n"
      in
      write ~format_as ~out (main ^ ".ml")
        (Print.structure ~header (main_module services))
  | None -> ());
  Option.iter
    (fun path ->
      Out_channel.with_open_text path (fun oc ->
          output_string oc
            "# Where the generated SDK uses Yojson.Safe.t: the spec allows any \
             JSON there.\n";
          Buffer.output_buffer oc untyped))
    (option args "--untyped");
  Printf.printf "%d operations in %d specs\n" !total_ops (List.length services)

let cases args =
  let specs = required args "--specs"
  and out = required args "--out"
  and format_as = required args "--format-as" in
  let library = required args "--library" in
  let services = List.map load (spec_files specs) in
  let header =
    "(* Generated by packages/sdk-ocaml/gen from packages/sdk/specs. Do not \
     edit. *)\n\n"
  in
  write ~format_as ~out "cases.ml"
    (Print.structure ~header (Emit_tests.structure ~library services))

let () =
  match Array.to_list Sys.argv with
  | _ :: "sdk" :: args -> sdk args
  | _ :: "cases" :: args -> cases args
  | _ -> usage ()
