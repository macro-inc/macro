//! `check node_modules nix` — verifies the fixed-output Bun `node_modules`
//! derivation still matches the committed lockfile/package manifests. Generated
//! into `check_node_modules_nix.yml`.

use gh_workflow::{Event, Job, PullRequest, Step, Workflow};

use crate::workflows::{runners, steps};

/// Build the workflow.
pub fn check_node_modules_nix() -> Workflow {
    Workflow::new("check node_modules nix")
        .on(Event::default().pull_request(
            PullRequest::default()
                .add_branch("main")
                .add_path("js/bun.lock")
                .add_path("js/**/package.json")
                .add_path("js/app/patches/**")
                .add_path("nix-support/node_modules.nix")
                .add_path("nix-support/node_modules-hashes.json")
                .add_path("nix/tauri-desktop.nix")
                .add_path("scripts/update-node-modules-hash.sh")
                .add_path("flake.nix")
                .add_path("flake.lock")
                .add_path(".github/workflows/check_node_modules_nix.yml"),
        ))
        .add_job("check-node-modules-nix", check_node_modules_nix_job())
}

fn check_node_modules_nix_job() -> Job {
    Job::default()
        .runs_on(runners::Runner::LinuxSmall.to_string())
        .add_step(steps::checkout(false))
        .add_step(steps::setup_nix())
        .add_step(steps::setup_cachix())
        .add_step(verify_node_modules_nix())
}

fn verify_node_modules_nix() -> Step<gh_workflow::Run> {
    Step::new("verify js node_modules derivation is up to date")
        .run("nix build .#js-node-modules .#js-node-modules-aarch64-darwin --no-link")
}
